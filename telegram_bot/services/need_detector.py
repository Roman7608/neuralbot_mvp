    def detect(self, text: str) -> Optional[ClientNeed]:
        """
        Определяет потребность клиента по тексту.
        
        :param text: Текст сообщения клиента
        :return: Определенная потребность или None
        """
        if not text:
            return None
        
        text_lower = text.lower()
        scores = {}

        # Явный приоритет кузовного цеха: ДТП/авария всегда маршрутизируем в кузовной,
        # даже если во фразе есть «оценить автомобиль» и т.п.
        if ("дтп" in text_lower) or ("авар" in text_lower):
            return ClientNeed.BODY_REPAIR

        # Явный приоритет слесарного цеха для развал-схождения и регулировки углов.
        if any(
            k in text_lower
            for k in (
                "развал",
                "развал схождение",
                "развал-схождение",
                "развал схождения",
                "регулировка углов установки колес",
                "регулировка углов установки колёс",
                "углы установки колес",
                "углы установки колёс",
                "углов установки колес",
                "углов установки колёс",
            )
        ):
            return ClientNeed.SERVICE
        
        # Подсчитываем совпадения для каждой потребности
        for need, keywords in self.KEYWORDS.items():
            score = 0
            for keyword in keywords:
                if keyword in text_lower:
                    score += 1
            if score > 0:
                scores[need] = score
        
        if not scores:
            return None
        
        # Кузовные ключевые слова имеют приоритет над СТО/слесарным
        if ClientNeed.BODY_REPAIR in scores and scores.get(ClientNeed.BODY_REPAIR, 0) > 0:
            if ClientNeed.SERVICE in scores:
                # Есть и кузовное, и слесарное — при наличии кузовных слов выбираем кузовной цех
                return ClientNeed.BODY_REPAIR
        
        best_need = max(scores.items(), key=lambda x: x[1])[0]
        logger.info(f"Определена потребность: {best_need.value} (score: {scores[best_need]})")
        return best_need
    
