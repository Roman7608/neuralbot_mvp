class RAGSystemStates:
    """
    RAG-система на основе стейтов (ключевые слова и правила).
    
    Использует систему правил для определения предзаписанного ответа
    вместо векторного поиска. Более предсказуемая и быстрая.
    """

    def __init__(
        self,
        audio_responses_dir: Path,
        similarity_threshold: float = RAG_SIMILARITY_THRESHOLD,
    ):
        """
        Инициализирует RAG-систему на основе стейтов.
        
        :param audio_responses_dir: Путь к директории с WAV-файлами
        :param similarity_threshold: Не используется в стейтах, оставлен для совместимости
        """
        self.audio_responses_dir = Path(audio_responses_dir)
        self.similarity_threshold = similarity_threshold
        
        # Компилируем регулярные выражения для каждого правила
        self.compiled_rules = []
        for rule in RESPONSE_RULES:
            compiled_keywords = [re.compile(keyword, re.IGNORECASE) for keyword in rule["keywords"]]
            self.compiled_rules.append({
                "wav_file": rule["wav_file"],
                "keywords": compiled_keywords,
                "priority": rule["priority"],
            })
        
        # Сортируем по приоритету (высокий приоритет первым)
        self.compiled_rules.sort(key=lambda x: x["priority"], reverse=True)
        
        logger.info(
            "Инициализирована RAG-система на основе стейтов "
            "(правил=%d, dir=%s)",
            len(self.compiled_rules),
            audio_responses_dir,
        )

    def find_best_response(
        self, transcript: str
    ) -> Optional[Tuple[str, float]]:
        """
        Находит наиболее подходящий предзаписанный ответ для транскрипта.
        
        :param transcript: Транскрипт речи клиента
        :return: Кортеж (путь к WAV-файлу, сходство) или None, если не найдено
        """
        if not transcript or not transcript.strip():
            return None
        
        transcript_lower = transcript.lower().strip()
        
        # Проверяем правила по приоритету
        for rule in self.compiled_rules:
            for keyword_pattern in rule["keywords"]:
                if keyword_pattern.search(transcript_lower):
                    wav_path = self.audio_responses_dir / rule["wav_file"]
                    if wav_path.exists():
                        logger.info(
                            "RAG найден ответ по правилу: %s (паттерн='%s', transcript='%s')",
                            rule["wav_file"],
                            keyword_pattern.pattern,
                            transcript[:50],
                        )
                        # Возвращаем сходство 1.0 для стейтов (точное совпадение)
                        return (str(wav_path), 1.0)
                    else:
                        logger.warning(
                            "WAV-файл не найден: %s (правило=%s)",
                            wav_path,
                            rule["wav_file"],
                        )
        
        logger.debug(
            "RAG не найден подходящий ответ (transcript='%s')",
            transcript[:50],
        )
        return None

    def _get_best_similarity(self, transcript: str) -> Tuple[float, Optional[str]]:
        """
        Внутренний метод для получения лучшего совпадения (для тестирования).
        
        :param transcript: Транскрипт речи клиента
        :return: Кортеж (сходство, имя WAV-файла)
        """
        result = self.find_best_response(transcript)
        if result:
            wav_path, similarity = result
            return (similarity, Path(wav_path).name)
        return (0.0, None)
