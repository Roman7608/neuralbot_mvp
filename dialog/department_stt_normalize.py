def normalize_department_stt_text(text: str) -> str:
    """Применяет подстановки искажений STT для распознавания отделов."""
    if not text:
        return text
    s = text.strip()
    if _RE_SHORT_TO.fullmatch(s):
        return "техобслуживание"
    if _RE_SHORT_KTO.fullmatch(s):
        return "техобслуживание"
    if _RE_SHORT_CHERY_DIGIT.fullmatch(s):
        return "чери"
    if _RE_SHORT_GARAN.fullmatch(s):
        return "гарантия"
    if _RE_SHORT_WARRANTY_STT.fullmatch(s):
        return "гарантия"
    if _RE_SHORT_ERVIS.fullmatch(s):
        return "сервис"
    if _RE_SHORT_SPECIERVIS.fullmatch(s):
        return "сервис"
    out = text
    if stt_implies_insurance_admin_department(out):
        return "администратор"
    # Б/У и «отдел продаж бу…» — до подстановки «продаж» → ОП Чери/Тенет.
    if stt_implies_used_cars_department(out):
        return "отдел автомобилей с пробегом"
    # Запчасти всегда приоритетнее любых «продаж» формулировок.
    if stt_implies_parts_department(out):
        return "отдел запасных частей"
    # Продажа без запчастей/БУ → единый ОП новых (Чери/Тенет)
    if re.search(r"(?i)\bпродаж(?:[аиуе])?\b", out) and not stt_implies_used_cars_department(out):
        out = re.sub(r"(?i)\bпродаж(?:[аиуе])?\b", "отдел продаж чери", out)
    for pattern, repl in _COMPILED:
        out = pattern.sub(repl, out)
    if stt_implies_parts_department(out):
        return "отдел запасных частей"
    # Любая отсылка к кузову (кузов, кузовной, кузовного, кузовный цех …) → канон для BODY
    if re.search(r"(?i)кузов", out):
        out = "цех кузовного ремонта"
    return out


def is_crm_site_outbound_callback(raw: str) -> bool:
    """
    Служебные фразы канала до/вместо имени: CRM («звонок с сайта», нажмите 5, …),
    АТС («обратный звонок», «повторная попытка дозвона», «для соединения», «с абонентом»,
    «нажмите кнопку ноль» / искажения вроде «0ль» и типичные искажения STT).

    Проверять по **исходному** тексту STT (до normalize_department_stt_text).
    """
    if not (raw or "").strip():
        return False
    t = (raw or "").lower()
    if "звонок с сайта" in t:
        return True
    # «нажмите 5», «нажмите кнопку пять», «абонентом нажмите кнопку пять» (эхо АТС/CRM).
    if re.search(r"нажмит[ея]\s+(?:кнопк\w+\s+)?(?:5|пять)\b", t):
        return True
    if "позвонить клиент" in t:
        return True
    if "чтобы позвонить" in t and "клиент" in t:
        return True
    if re.search(
        r"звонок\s+с\s+сайта[\s\S]{0,160}нажмит[ея]\s+(?:кнопк\w+\s+)?(?:5|пять)\b[\s\S]{0,120}позвонить\s+клиент",
        t,
    ):
        return True
    if re.search(r"нажмит[ея]\s+(?:кнопк\w+\s+)?(?:5|пять)\b[\s\S]{0,100}позвонить\s+клиент", t):
        return True
    # --- АТС / исходящий колбэк (тот же мгновенный перевод на администратора, что у CRM) ---
    if re.search(r"обратн\w*\s+звон", t) or re.search(r"звон\w*\s+обратн\w*", t):
        return True
    if re.search(r"повторн\w*\s+попытк", t) and (
        "дозвон" in t or re.search(r"до\s+звон", t)
    ):
        return True
    # --- IVR / соединение (эхо в канале до ответа клиента) ---
    if "для соединения" in t:
        return True
    if "с абонентом" in t:
        return True
    if "кнопку ноль" in t or "кнопку 0ль" in t:
        return True
    # Цифра «0» в STT («нажмите кнопку 0») — раньше ловили только слово «ноль» и «0ль».
    if "кнопку 0" in t or "кнопке 0" in t:
        return True
    if re.search(r"нажми[те]?\s+кнопк\w*\s+(?:ноль|0ль|0\s*ль|0\b)", t):
        return True
    return False


def _site_tenet_or_form_stt(raw: str) -> bool:
    """
    Робот с сайта / форма: «Сайт Тенет», tnt, «Имя клиента …».
    Проверка по исходному STT (до normalize_department_stt_text).
    """
    if not (raw or "").strip():
        return False
    t = (raw or "").lower()
    # Шаблон CRM «Имя клиента Владимир» / в середине фразы
    if re.search(r"(?i)(?:^|[\s,;])имя\s+клиент", t):
        return True
    # «Сайт Тенет», «Сайт tenet», «сайт tnt», латиница
    if re.search(r"(?i)сайт\s*[:\s]*(?:тенет|тэнет|tenet|tnt)[\w\.]*", t):
        return True
    if re.search(r"(?i)\b(?:tnt\.?\s*r|tnt\.?ru|tenet\.ru)\b", t):
        return True
    if re.search(r"(?i)тенет\s*\.?\s*ру\b", t):
        return True
    if "сайт" in t and re.search(r"(?i)(?:тенет|тэнет|tenet|\btnt\b)", t):
        return True
    return False


def is_silent_immediate_admin_callback(raw: str) -> bool:
    """
    Единый триггер «молча на администратора» (рабочее и нерабочее):
    весь is_crm_site_outbound_callback (нажмите 5, звонок с сайта, АТС/IVR …),
    «нажмите 1», формы «Сайт Тенет» / tnt / «Имя клиента …».

    Проверять по **исходному** тексту STT (до normalize_department_stt_text).
    """
    if not (raw or "").strip():
        return False
    if is_crm_site_outbound_callback(raw):
        return True
    t = (raw or "").lower()
    if re.search(r"нажми[те]?\s*(?:1|один)\b", t):
        return True
    if _site_tenet_or_form_stt(raw):
        return True
    return False


