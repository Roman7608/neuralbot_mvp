# Намерение «отдел запчастей»: сильнее кузова и прочих отделов (см. normalize + bot_logic).
_PARTS_INTENT_RE = re.compile(
    r"(?i)запчаст|зачаст|зап\.?\s*част|зопчаст|запасн\w*\s+част|запаисн\w*\s+част|запаясн\w*\s+част|"
    r"запки\s+част|"
    r"\bзапа\b|\bзапасные\b(?:\s+част\w*)?|отдел\s+зч\b|отдел\s+зап\b|склад\s+запчаст",
    re.UNICODE,
)

# Слово «запа» + ещё буквы → запчасти (STT-обрубки и опечатки). Исключаем явно не те смыслы.
_ZAPA_WORD_RE = re.compile(r"(?i)\bзапа\w+\b", re.UNICODE)
_ZAPA_NOT_PARTS_PREFIXES = (
    "запад",
    "запах",
    "запал",
    "запасть",
    "запар",  # запарка, запарить
)


def _word_starting_zapa_implies_parts(word: str) -> bool:
    low = (word or "").lower()
    if len(low) < 5 or not low.startswith("запа"):
        return False
    return not any(low.startswith(p) for p in _ZAPA_NOT_PARTS_PREFIXES)


def _apply_parts_stt_typos(s: str) -> str:
    """Лёгкая правка STT для проверки запчастей (без полного normalize — нет рекурсии)."""
    return re.sub(r"(?i)\bзачаст", "запчаст", s or "")


def stt_implies_parts_department(text: str) -> bool:
    """True, если реплика однозначно про отдел запасных частей (в т.ч. «запчасти на кузов»)."""
    if not (text or "").strip():
        return False
    for chunk in (text, _apply_parts_stt_typos(text)):
        if _PARTS_INTENT_RE.search(chunk):
            return True
        if any(_word_starting_zapa_implies_parts(m.group(0)) for m in _ZAPA_WORD_RE.finditer(chunk)):
            return True
    return False


