def format_slot_confirm_reprompt_tts(
    day_text: str | None = None,
    month_tts: str | None = None,
    time_tts: str | None = None,
) -> str:
    """Короткий переспрос после предложения слота.

    Если переданы дата и время — повторяем их, чтобы клиент не терял контекст.
    """
    if day_text and month_tts and time_tts:
        text = (
            f"Запис+ать Вас на {day_text} {month_tts} в {time_tts}?? "
            f"Скажите «записывай» или назовите другую дату."
        )
        return apply_silero_question_intonation(text)
    return apply_silero_question_intonation(SLOT_CONFIRM_REPROMPT)


def format_service_slot_offer_tts(
    day_text: str,
    month_tts: str,
    time_tts: str,
    *,
    slot_hhmm: str | None = None,
    unavailable_day_text: str | None = None,
    unavailable_month_tts: str | None = None,
) -> str:
    """Предложение слота: подтверждение «Запишу Вас на …?» (Silero, вопросительная интонация).

    Если слот на другой день, чем просил клиент, сначала: «нет свободных слотов».
    """
    from dialog.service_slot_day_part import slot_needs_next_day_pickup

    prefix = ""
    if unavailable_day_text and unavailable_month_tts:
        prefix = (
            f"К сожалению, на {unavailable_day_text} {unavailable_month_tts} "
            f"нет свободных слотов. "
        )
    base = prefix + f"Запишу Вас на {day_text} {month_tts} в {time_tts}?"
    if slot_hhmm and slot_needs_next_day_pickup(slot_hhmm):
        # Примечание про выдачу на следующий день — до вопроса подтверждения.
        base = (
            prefix
            + f"На {day_text} {month_tts} в {time_tts} есть свободное вр+емя."
            + NEXT_DAY_PICKUP_SLOT_TTS
            + f" Запишу Вас на {day_text} {month_tts} в {time_tts}?"
        )
    return apply_silero_question_intonation(base)


