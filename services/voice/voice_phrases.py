# Silero: «??» в конце поднимает интонацию; без пауз «...» посередине фразы.
_QUESTION_INTONATION_REPLACEMENTS: tuple[tuple[str, str], ...] = (
    (r"Записать в\+ас\?$", "Мог+у записать в+ас??"),
    (r"Записать на это время или назовите другую дату\?$", "Записать на это время или назовите другую дату??"),
    (r"Записать или выберете другую дату\?$", "Записать или выберете другую дату??"),
    (r"Всё верно\?$", "Всё в+ерно??"),
    (r", верно\?$", ", в+ерно??"),
    (r"верно\?$", "в+ерно??"),
    (r"перевести\?$", "перевести??"),
    (r"вопросы\?$", "вопросы??"),
    (r"помочь\?$", "помочь??"),
    (r"интересует\?$", "интересует??"),
    (r"зовут\?$", "зовут??"),
    (r"соединить\?$", "соединить??"),
)


def apply_silero_question_intonation(text: str) -> str:
    """Вопросительная интонация Silero для фраз, оканчивающихся на «?»."""
    import re

    t = (text or "").strip()
    if not t.endswith("?") or t.endswith("??"):
        return text
    for pattern, repl in _QUESTION_INTONATION_REPLACEMENTS:
        new_t, n = re.subn(pattern, repl, t, count=1, flags=re.IGNORECASE)
        if n:
            return new_t
    return t[:-1] + "??"


