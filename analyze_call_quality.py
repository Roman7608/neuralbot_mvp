def _is_plausible_manager_name(name: str, strict: bool = False) -> bool:
    """Кандидат в имя менеджера: отсекаем мусор (блоклист), одно слово — только из справочника имён."""
    if not name or len(name) < 2:
        return False
    parts = name.lower().split()
    if any(p in NON_NAMES_BLOCKLIST for p in parts):
        return False
    if len(parts) == 1:
        w = parts[0]
        # 19212: «Мастприёмщик» — роль STT, не имя. Однословные подписи только из
        # data/russian_first_names.txt (COMMON_NAMES) или известных фамилий.
        if w in COMMON_NAMES or w in KNOWN_SURNAMES:
            return True
        return False
    if len(parts) == 2:
        first, second = parts
        if _is_dealer_brand_location_not_person_name(name):
            return False
        if strict:
            return first in COMMON_NAMES and (second in COMMON_NAMES or second in KNOWN_SURNAMES)
        return (len(first) >= 2 and len(second) >= 2 and first.isalpha() and second.isalpha())
    return False


