def _pick_best_staff_intro_from_candidates(
    full_text: str,
    department: Optional[str],
    candidates: List[Tuple[int, int, str, str]],
) -> Optional[str]:
    """Лучшее представление: после последнего перевода, по score; слабое до перевода отбрасывается."""
    if not candidates:
        return None
    low = (full_text or "").lower()
    h_end = _last_handover_end_pos(low)
    validated: List[Tuple[int, int, str, str, str]] = []
    for pos, score, raw, kind in candidates:
        if kind == "name_before_master":
            if not _is_valid_manager_name_from_catalog(raw):
                continue
            fn = _nom_firstname_low(raw.split()[0])
            out = _firstname_only_display(fn)
        elif kind == "anchor_window":
            fn = raw.split()[0]
            out = _canonicalize_service_intro_given_name(fn)
            if not out and _is_valid_manager_name_from_catalog(fn):
                out = fn.title()
        elif kind == "menya_zovut_vas_client":
            fn = raw.split()[0]
            out = fn.title() if _is_valid_manager_name_from_catalog(fn) else None
        else:
            out = _check_manager_name(
                full_text,
                raw,
                pos,
                low,
                intro_context=True,
                department=department,
            )
        if not out:
            svc = _canonicalize_service_intro_given_name(raw.split()[0])
            if svc and kind == "service_role":
                out = svc
            elif kind == "dept" and _is_valid_manager_name_from_catalog(raw.split()[0]):
                out = raw.split()[0].title()
        if not out:
            continue
        validated.append((pos, score, raw, kind, out))

    if not validated:
        return None

    def eligible(pos: int, score: int, kind: str) -> bool:
        if h_end <= 0:
            return True
        if pos >= h_end:
            return True
        if kind == "admin":
            return False
        if kind in ("anchor_window", "dept_intro_name"):
            return pos >= h_end or score >= 120
        if score >= 120:
            return True
        return False

    def rank_score(pos: int, score: int, kind: str, raw: str) -> int:
        rs = score
        if kind in _SELF_INTRO_MANAGER_KINDS:
            rs += 25
        if kind in ("x_eto_mgr", "eto_op_mgr", "name_mgr") and _is_valid_manager_name_from_catalog(
            raw.split()[0] if raw.split() else raw
        ):
            rs += 15
        if h_end > 0 and pos >= h_end and kind == "client_then_mgr":
            rs += 30
        if h_end > 0 and pos >= h_end and kind in ("menya_zovut", "anchor_window"):
            rs += 15
        return rs

    pool = [v for v in validated if eligible(v[0], v[1], v[3])]
    if not pool and h_end > 0:
        pool = [v for v in validated if v[0] >= h_end]
    if h_end > 0 and _transcript_is_insurance_body_reception_not_op_sales(full_text):
        after_h_pool = [v for v in pool if v[0] >= h_end]
        if after_h_pool:
            pool = after_h_pool
    if not pool:
        pool = [v for v in validated if v[3] != "admin"]
    if not pool:
        return None

    self_pool = [v for v in pool if v[3] in _EXPLICIT_STAFF_SELF_INTRO_KINDS]
    if self_pool:
        after_h = [v for v in self_pool if h_end <= 0 or v[0] >= h_end]
        pick_from = after_h if after_h else self_pool
        def _self_intro_pick_key(v: Tuple[int, int, str, str, str]) -> Tuple[int, int]:
            pos, sc, raw, kind, _out = v
            rs = rank_score(pos, sc, kind, raw)
            return (rs, pos)

        _pos, _sc, _raw, _kind, best_out = max(pick_from, key=_self_intro_pick_key)
        if _kind == "name_before_master":
            return best_out
        if _kind == "anchor_window":
            return best_out
        return _require_canonical_manager_display(
            _canonicalize_manager_display(best_out, department), department
        )

    pool.sort(key=lambda v: (-rank_score(v[0], v[1], v[3], v[2]), v[0]))
    _pos, _sc, _raw, _kind, best_out = pool[0]
    if _kind == "name_before_master":
        return best_out
    if _kind == "anchor_window":
        return best_out
    return _require_canonical_manager_display(
        _canonicalize_manager_display(best_out, department), department
    )


def _extract_manager_from_ranked_staff_intros(
    full_text: str, department: Optional[str]
) -> Optional[str]:
    cands = _collect_staff_intro_candidates(full_text, department)
    return _pick_best_staff_intro_from_candidates(full_text, department, cands)


