    has_call_before = any(
        w in closing_part for w in ["созвонимся", "созвонитесь", "перезвоню", "перезвоним", "накануне"]
    )

    if not has_attempt and not has_day and not has_time:
        # Нет даже попытки назначить визит
        closing_score = 0.0
    elif has_day and has_time and has_call_before:
        # День, время и предварительный созвон
        closing_score = 1.0
    elif has_day and (has_time or has_call_before):
        # Есть договорённость о дне и либо время, либо созвон
        closing_score = 0.75
    else:
        # Просто попытка назначить визит без чётких договорённостей
        closing_score = 0.25
    scores["closing"] = closing_score

