def _try_ambiguous_firstname_manager(full_text: str, department: str, rows: list) -> Optional[str]:
    """
    Несколько сотрудников в справочнике с одним именем, в тексте нет фамилии для различения —
    возвращаем только имя («Юлия», «Андрей») по устойчивым шаблонам представления.
    """
    ambiguous = _ambiguous_firstname_to_manager_keys(rows)
    if not ambiguous:
        return None
    low = (full_text or "").lower()

    if department == "STO":
        # СТО: «диспетчер сервиса Юлия» / склейки STT «диспетчерсервис. Юлия»
        sto_mgr_intro = [
            r"\b(?:диспетчер|ассистент)\s+сервиса\s+([а-яё]+)\b",
            r"\b([а-яё]+)\s*,\s*диспетчер\s+сервиса\b",
            r"\bдиспетчерсервиса\b[.\s,:;!?«»\-–—]*\s*([а-яё]+)\b",
            r"\bдиспетчерсервис\b[.\s,:;!?«»\-–—]*\s*([а-яё]+)\b",
            r"\b(?:диспетчер|ассистент)\s+сервис\b[.\s,:;!?«»\-–—]*\s*([а-яё]+)\b",
        ]
        for pat in sto_mgr_intro:
            m = re.search(pat, low, flags=re.IGNORECASE)
            if not m:
                continue
            nom = _nom_firstname_low(m.group(1))
            if nom in ambiguous:
                return _firstname_only_display(nom)
        return None

    if department == "OP":
        if _transcript_blocks_op_roster_by_service_role(full_text):
            return None
        for fn_low, keys in ambiguous.items():
            if not re.search(rf"\b{re.escape(fn_low)}\b", low):
                continue
            if any(re.search(rf"\b{re.escape(k.lower())}\b", low) for k in keys):
                continue
            for m2 in re.finditer(rf"\b{re.escape(fn_low)}\b", low):
                ctx = low[max(0, m2.start() - 120) : m2.end() + 90]
                if re.search(
                    r"(?:менеджер|отдела\s+продаж|викинги|чери|тенет|это|меня\s+зовут|"
                    r"добрый\s+день|добрый\s+вечер|здравствуйте)",
                    ctx,
                ):
                    return _firstname_only_display(fn_low)
        return None

    return None


def _extract_manager_by_directory(full_text: str, department: str) -> Optional[str]:
    """
    Справочник ОП/СТО: сначала фамилия в тексте; для ОП, если фамилии нет — одно имя
    достаточно только если в справочнике ровно один менеджер с таким именем (два «Андрей» —
    нужна фамилия). Возвращает display (Фамилия Имя), либо только имя при неоднозначности
    (несколько Юлий / Андреев в справочнике и нет фамилии в транскрипте).
    """
    try:
        from admin_panel.managers_config import OP_MANAGERS, STO_MANAGERS

        rows = OP_MANAGERS if department == "OP" else STO_MANAGERS if department == "STO" else []
    except ImportError:
        rows = []
    if not rows:
        return None
    low = (full_text or "").lower()
    # STT-варианты имени Дарья на линии СТО: «дария/дарий/дарию/дарием».
    # Без нормализации не матчится справочник STO_MANAGERS.
    low = re.sub(r"\bдария\b", "дарья", low)
    low = re.sub(r"\bдарий\b", "дарья", low)
    low = re.sub(r"\bдарию\b", "дарью", low)
    low = re.sub(r"\bдарием\b", "дарьей", low)
    # STT: «Андреев Юлюсс, Слушаюс» / «Мадреева Юли» на линии диспетчера (14443 и др.).
    low = re.sub(r"\b(?:мадреев|адреев)а\b", "андреева", low)
    low = re.sub(r"\bандреевой\b", "андреева", low)
    low = re.sub(r"\bандреев\b", "андреева", low)
    low = re.sub(r"\bюлюсс\b", "юлия", low)
    low = re.sub(r"\bюляя\b", "юлия", low)
    # Сильные: фамилия/алиас фамилии в тексте. Слабые: только имя из справочника (часто клиент).
    hits_strong: List[Tuple[int, str]] = []
    hits_weak: List[Tuple[int, str]] = []

    for m in rows:
        key = m["manager_name"]
        sur = key.lower()
        for mo in re.finditer(r"\b" + re.escape(sur) + r"\b", low):
            hits_strong.append((mo.start(), key))

    # STT-вариативность фамилий (ОП/СТО): мягкие regex-алиасы для опечаток и "проглотов" гласных.
    # Применяем в рамках выбранного справочника отдела, чтобы не уводить в ложные совпадения.
    surname_alias_patterns: Dict[str, Tuple[str, ...]] = {
        "Евдокимов": (r"евд[оа]к[ииеё]м[оа]в[а-яё]*",),
        "Захаров": (r"захар[оа]в[а-яё]*",),
        "Краснощекова": (
            r"красн[оа]щ[еёи]к[оа]в[а-яё]*",
            r"красн[оа]щ[еёи]к[ао]в[а-яё]*",
            # STT часто: «Краснощук Анастасия» без «ков»
            r"краснощук\b",
            r"красн[оа]щук\b",
            r"краснощуков[а-яё]*",
            r"крастостук\b",
        ),
        "Щеголев": (
            r"щ[еёи]г[оа]?л{1,2}[еёи]?[вф][а-яё]*",
            r"ш[еёи]г[оа]?л{1,2}[еёи]?[вф][а-яё]*",
            r"щг[оа]?л{1,2}[еёи]?[вф][а-яё]*",
        ),
        "Калаев": (r"кал[ао][еёи]?[вф][а-яё]*",),
        "Плаксина": (r"плакс[иы]н[аоыуеё][а-яё]*",),
        "Андреева": (r"андр[еёи]{1,2}в(?:[аоыуеё][а-яё]*)?\b",),
        "Гринкина": (
            r"гр[ие][нн]к[иы]н[аоыуеё][а-яё]*",
            r"гранк[иы]н[аоыуеё][а-яё]*",
        ),
    }
    valid_keys = {m["manager_name"] for m in rows}
    for canon_key, patterns in surname_alias_patterns.items():
        if canon_key not in valid_keys:
            continue
        for pat in patterns:
            for mo in re.finditer(r"\b" + pat + r"\b", low):
                hits_strong.append((mo.start(), canon_key))

    if department == "STO":
        for alias, canon in (
            ("гранкина", "Гринкина"),
            ("гренкина", "Гринкина"),
            ("плаксон", "Плаксина"),
            ("плаксин", "Плаксина"),
        ):
            for mo in re.finditer(r"\b" + re.escape(alias) + r"\b", low):
                hits_strong.append((mo.start(), canon))
        if (
            not hits_strong
            and not hits_weak
            and _transcript_has_sto_service_signals_for_manager_roster(full_text)
        ):
            for mo in re.finditer(r"\bалександра\b", low):
                if _skip_sto_alexandra_as_patronymic_reference(low, mo.start()):
                    continue
                hits_strong.append((mo.start(), "Плаксина"))
                break
            if re.search(r"\bюлия\b", low) or re.search(r"\bюлию\b", low):
                mo_a = re.search(r"\bандреева\b", low)
                mo_g = re.search(r"\bгринкина\b", low) or re.search(r"\bгранкина\b", low)
                if mo_a and not mo_g:
                    hits_strong.append((mo_a.start(), "Андреева"))
                elif mo_g and not mo_a:
                    hits_strong.append((mo_g.start(), "Гринкина"))

    # ОП: сначала однозначные совпадения по имени (единственный «Анастасия» в справочнике),
    # иначе неоднозначный блок ниже вернёт только «Андрей» без фамилии раньше явного «Меня зовут Анастасия».
    if department == "OP":
        by_first: Dict[str, List] = {}
        for m in rows:
            disp_parts = (m.get("display") or "").strip().split()
            if len(disp_parts) >= 2:
                fn = disp_parts[1].lower()
                by_first.setdefault(fn, []).append(m)
        for fn, mgr_list in by_first.items():
            if len(mgr_list) != 1:
                continue
            m0 = mgr_list[0]
            key0 = m0["manager_name"]
            for mo in re.finditer(r"\b" + re.escape(fn) + r"\b", low):
                if _skip_op_firstname_as_outbound_client_greeting(full_text, mo.start(), fn):
                    continue
                if _skip_op_firstname_as_client_patronymic_greeting(full_text, mo.start(), fn):
                    continue
                if _skip_op_firstname_as_sto_priyom_or_service_role(full_text, mo.start(), fn):
                    continue
                if _skip_op_firstname_as_lead_line_client_name(full_text, mo.start(), fn):
                    continue
                hits_weak.append((mo.start(), key0))

    hits = hits_strong if hits_strong else hits_weak
    if department == "OP" and _transcript_blocks_op_roster_by_service_role(full_text):
        hits = hits_strong if hits_strong else []

    if not hits_strong and not hits_weak:
        amb_only = _try_ambiguous_firstname_manager(full_text, department, rows)
        if amb_only:
            return amb_only
    if not hits_strong and not hits_weak and department == "STO":
        # Для СТО допускаем имя без фамилии (две Юлии в справочнике и т.д.).
        if re.search(r"\bюли(?:я|ю)\b|\bюля\b", low):
            return "Юлия"
        if re.search(r"\bалександр[ауы]\b", low):
            return "Александра"
        if re.search(r"\bдарь[яю]\b", low):
            return "Дарья"

    if not hits:
        return None
    by_key: Dict[str, int] = {}
    for pos, key in hits:
        if key not in by_key or pos < by_key[key]:
            by_key[key] = pos
    ordered = sorted(by_key.keys(), key=lambda k: by_key[k])
    key = ordered[0]
    try:
        from admin_panel.managers_config import display_for_manager_key

        disp = display_for_manager_key(key, department)
        if disp:
            parts = [p for p in disp.strip().split() if p]
            if len(parts) >= 2:
                return f"{parts[1]} {parts[0]}"
            return disp
        return key
    except ImportError:
        return key


