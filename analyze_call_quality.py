def client_self_intro_in_text(text: str, manager_name: Optional[str] = None) -> bool:
    """
    Клиент представился («меня зовут X»), а не менеджер.
    Если менеджер сам назвался — это не засчитывается как самопредставление клиента.
    """
    mgr_tokens = _manager_name_tokens(manager_name)
    for m in re.finditer(
        r"(?<![а-яё])меня\s+зовут\s+([а-яё]{2,20})\b",
        text or "",
        flags=re.IGNORECASE,
    ):
        name = m.group(1).lower().replace("ё", "е")
        if name in mgr_tokens:
            continue
        if _is_manager_self_intro_tail(text, m.end()):
            continue
        if name in COMMON_NAMES or any(k.startswith(name[:3]) for k in COMMON_NAMES if len(name) >= 3):
            return True
    return False


