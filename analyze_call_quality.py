def _gigaam_dial_tone_detection_params() -> Tuple[float, float, float]:
    """Пороги детектора тона (гудки перевода): см. GIGAAM_TONE_* в env."""
    hz_min = float(os.environ.get("GIGAAM_TONE_HZ_MIN", "200"))
    hz_max = float(os.environ.get("GIGAAM_TONE_HZ_MAX", "1000"))
    peak_ratio = float(os.environ.get("GIGAAM_TONE_PEAK_RATIO", "0.08"))
    return hz_min, hz_max, peak_ratio


def detect_dial_tone_end(file_path: Path, max_search_sec: float = 60.0) -> float:
    """
    Ищет конец гудков в начале файла по спектру (узкий пик в полосе GIGAAM_TONE_HZ_*).
    Возвращает время в секундах, с которого начинается «речь»; 0 если гудки не найдены.
    """
    try:
        hz_min, hz_max, peak_ratio = _gigaam_dial_tone_detection_params()
        audio, sr = sf.read(str(file_path))
        if len(audio.shape) > 1:
            audio = audio[:, 0]
        duration = len(audio) / sr
        if duration < 2.0:
            return 0.0
        # Окно 1 с, шаг 0.5 с; ищем только в начале
        window_len = int(sr)
        step = int(sr * 0.5)
        n_windows = min(int(max_search_sec * sr / step), (len(audio) - window_len) // step + 1)
        if n_windows < 2:
            return 0.0
        tone_count = 0
        for k in range(n_windows):
            start = k * step
            chunk = audio[start : start + window_len].astype(np.float64)
            if len(chunk) < window_len:
                break
            energy = np.sqrt(np.mean(chunk ** 2))
            if energy < 1e-5:
                if tone_count >= 2:
                    return (start + window_len) / sr
                tone_count = 0
                continue
            # FFT, ищем доминантную частоту
            nfft = min(4096, len(chunk))
            spec = np.abs(np.fft.rfft(chunk, n=nfft))
            freqs = np.fft.rfftfreq(nfft, 1.0 / sr)
            # только 100–2000 Hz
            mask = (freqs >= 100) & (freqs <= 2000)
            if not np.any(mask):
                if tone_count >= 2:
                    return start / sr
                continue
            peak_idx = np.argmax(spec[mask])
            peak_hz = freqs[mask][peak_idx]
            peak_val = spec[mask][peak_idx]
            total = np.sum(spec[mask])
            if total < 1e-10:
                continue
            # Гудок: узкий пик в типичном диапазоне
            is_tone = hz_min <= peak_hz <= hz_max and (peak_val / total) > peak_ratio
            if is_tone:
                tone_count += 1
            else:
                if tone_count >= 2:
                    return start / sr
                tone_count = 0
        return 0.0
    except Exception as e:
        print(f"  ⚠️  Детектор гудков: {e}", flush=True)
        return 0.0


def _gigaam_window_is_dial_tone(
    chunk: np.ndarray,
    sr: int,
    hz_min: float,
    hz_max: float,
    peak_ratio: float,
) -> bool:
    """Узкополосный тон в полосе hz_min–hz_max; доля пика в спектре > peak_ratio."""
    if len(chunk) < 256:
        return False
    chunk = chunk.astype(np.float64)
    energy = np.sqrt(np.mean(chunk**2))
    if energy < 1e-5:
        return False
    nfft = min(4096, len(chunk))
    spec = np.abs(np.fft.rfft(chunk, n=nfft))
    freqs = np.fft.rfftfreq(nfft, 1.0 / sr)
    mask = (freqs >= 100) & (freqs <= 2000)
    if not np.any(mask):
        return False
    peak_idx = np.argmax(spec[mask])
    peak_hz = freqs[mask][peak_idx]
    peak_val = spec[mask][peak_idx]
    total = np.sum(spec[mask])
    if total < 1e-10:
        return False
    return bool(hz_min <= peak_hz <= hz_max and (peak_val / total) > peak_ratio)


def _merge_sample_intervals(intervals: List[Tuple[int, int]]) -> List[Tuple[int, int]]:
    if not intervals:
        return []
    intervals = sorted(intervals)
    merged: List[List[int]] = [list(intervals[0])]
    for a, b in intervals[1:]:
        if a <= merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], b)
        else:
            merged.append([a, b])
    return [(int(x[0]), int(x[1])) for x in merged]


def _detect_dial_tone_regions_mono(
    audio: np.ndarray,
    sr: int,
    min_duration_sec: float,
) -> List[Tuple[int, int]]:
    """Находит интервалы узкополосного тона по всей длине моно-сигнала."""
    out = np.asarray(audio, dtype=np.float32)
    wl = int(0.5 * sr)
    step = int(0.25 * sr)
    if wl < 256:
        return []
    hz_min, hz_max, peak_ratio = _gigaam_dial_tone_detection_params()
    regions: List[Tuple[int, int]] = []
    pos = 0
    while pos + wl <= len(out):
        if _gigaam_window_is_dial_tone(
            out[pos : pos + wl], sr, hz_min, hz_max, peak_ratio
        ):
            regions.append((pos, pos + wl))
        pos += step
    merged = _merge_sample_intervals(regions)
    min_samples = int(min_duration_sec * sr)
    return [(a, b) for a, b in merged if (b - a) >= min_samples]


def _find_transfer_split_sec(
    tone_regions: List[Tuple[int, int]],
    sr: int,
    duration_sec: float,
) -> float:
    """
    Возвращает точку разреза (конец «гудков перевода») в середине файла.
    0.0 — если подходящий участок не найден.
    """
    if not tone_regions:
        return 0.0
    min_start = float(os.environ.get("GIGAAM_SPLIT_MIN_START_SEC", "5.0"))
    min_tail = float(os.environ.get("GIGAAM_SPLIT_MIN_TAIL_SEC", "5.0"))
    # Берём самый длинный «тональный» интервал в середине записи.
    best = None
    best_len = -1
    for a, b in tone_regions:
        start_sec = a / sr
        end_sec = b / sr
        if start_sec < min_start:
            continue
        if (duration_sec - end_sec) < min_tail:
            continue
        cur_len = b - a
        if cur_len > best_len:
            best_len = cur_len
            best = (start_sec, end_sec)
    if not best:
        return 0.0
    return best[1]


def strip_dial_tone_regions_mono(
    audio: np.ndarray,
    sr: int,
    min_duration_sec: float = 0.15,
    max_stripped_frac: float = 0.42,
) -> Tuple[np.ndarray, float]:
    """
    По всей длине моно: окна, похожие на тональные гудки, заменяются нулями.
    Длина и тайминг записи не меняются — только убираем сигнал, вводящий STT в заблуждение.

    Возвращает (audio_out, stripped_seconds). Если срезано слишком много — возвращает исходное аудио и 0.0.
    """
    if audio.size == 0 or sr < 8000:
        return audio, 0.0
    out = np.asarray(audio, dtype=np.float32).copy()
    strip_ranges = _detect_dial_tone_regions_mono(
        out, sr, min_duration_sec=min_duration_sec
    )
    if not strip_ranges:
        return out, 0.0
    total_strip_samples = sum(b - a for a, b in strip_ranges)
    if total_strip_samples > max_stripped_frac * len(out):
        print(
            "  ⚠️  Подавление гудков отменено: слишком большая доля файла под «тон»",
            flush=True,
        )
        return np.asarray(audio, dtype=np.float32), 0.0
    for a, b in strip_ranges:
        out[a:b] = 0.0
    stripped_sec = total_strip_samples / float(sr)
    return out, stripped_sec


def trim_audio_after(file_path: Path, start_sec: float) -> Optional[Path]:
    """Обрезает аудио с start_sec до конца, сохраняет во временный WAV. Возвращает путь к файлу или None."""
    import tempfile
    try:
        audio, sr = sf.read(str(file_path))
        if len(audio.shape) > 1:
            audio = audio[:, 0]
        start_sample = int(start_sec * sr)
        if start_sample >= len(audio):
            return None
        trimmed = audio[start_sample:]
        fd, path = tempfile.mkstemp(suffix=".wav")
        os.close(fd)
        sf.write(path, trimmed, sr)
        return Path(path)
    except Exception as e:
        print(f"  ⚠️  Обрезка аудио: {e}", flush=True)
        return None


def load_gigaam_model_from_path(path: Path) -> object:
    """
    Загрузка GigaAM-v3 из указанной папки (e2e_ctc, e2e_rnnt и т.д.).
    Предзагрузка: python download_gigaam.py
    """
    try:
        from transformers import AutoModel
    except ImportError:
        raise RuntimeError(
            "Модуль transformers не установлен. Для GigaAM: pip install -r requirements-gigaam.txt"
        )
    path = Path(path)
    if not (path / "config.json").exists():
        raise FileNotFoundError(
            f"GigaAM-v3 не найдена в {path}. "
            "Запустите один раз при наличии интернета: python download_gigaam.py"
        )
    print(f"  🔧 GigaAM-v3: загрузка из {path} (офлайн)...", flush=True)
    # Патч для meta tensors в torchaudio melscale_fbanks (PyTorch 2.8)
    import torch
    from torchaudio import functional as F_ta
    from torchaudio.functional import functional as _F_impl

    _orig_melscale_fbanks = F_ta.melscale_fbanks

    def _patched_melscale_fbanks(n_freqs, f_min, f_max, n_mels, sample_rate, norm=None, mel_scale="htk"):
        import warnings
        if norm is not None and norm != "slaney":
            raise ValueError('norm must be one of None or "slaney"')
        all_freqs = torch.linspace(0, sample_rate // 2, n_freqs)
        m_min = _F_impl._hz_to_mel(f_min, mel_scale=mel_scale)
        m_max = _F_impl._hz_to_mel(f_max, mel_scale=mel_scale)
        m_pts = torch.linspace(m_min, m_max, n_mels + 2)
        f_pts = _F_impl._mel_to_hz(m_pts, mel_scale=mel_scale)
        fb = _F_impl._create_triangular_filterbank(all_freqs, f_pts)
        if norm is not None and norm == "slaney":
            enorm = 2.0 / (f_pts[2 : n_mels + 2] - f_pts[:n_mels])
            fb *= enorm.unsqueeze(0)
        try:
            if (fb.max(dim=0).values == 0.0).any():
                warnings.warn(
                    f"At least one mel filterbank has all zero values. n_mels={n_mels}, n_freqs={n_freqs}"
                )
        except RuntimeError as e:
            if "meta tensors" not in str(e):
                raise
        return fb

    F_ta.melscale_fbanks = _patched_melscale_fbanks
    # Патч _finalize_model_loading — GigaAM может не иметь all_tied_weights_keys (transformers API)
    from transformers import modeling_utils
    _orig_finalize = modeling_utils.PreTrainedModel._finalize_model_loading

    def _patched_finalize(model, load_config, loading_info):
        if not hasattr(model, "all_tied_weights_keys"):
            model.all_tied_weights_keys = getattr(model, "_tied_weights_keys", None) or {}
        _call = getattr(_orig_finalize, "__func__", _orig_finalize)
        return _call(model, load_config, loading_info)

    modeling_utils.PreTrainedModel._finalize_model_loading = staticmethod(_patched_finalize)
    try:
        model = AutoModel.from_pretrained(
            str(path),
            trust_remote_code=True,
            local_files_only=True,
            low_cpu_mem_usage=False,
        )
    finally:
        F_ta.melscale_fbanks = _orig_melscale_fbanks
        modeling_utils.PreTrainedModel._finalize_model_loading = _orig_finalize
    model.eval()
    try:
        import torch
        if torch.cuda.is_available():
            model = model.cuda()
            print(f"  🔧 GPU: {torch.cuda.get_device_name(0)}", flush=True)
    except Exception:
        pass
    return model


def load_gigaam_model():
    """Загрузка GigaAM-v3 из GIGAAM_MODEL_PATH (config)."""
