def _failed_service_handoff_salon_admin(full_text: str) -> Optional[str]:
    """
    Администратор пытался перевести на мастера/специалиста, но тот не подключился,
    поэтому сотрудником звонка остаётся администратор. Имя названного целевого
    мастера до перевода не является самопредставлением.
    """
    ft = full_text or ""
    low = ft.lower()
    salon_admin = _extract_salon_admin_manager_name(ft)
    if not salon_admin:
        return None
    handover_end = _last_handover_end_pos(low)
    if handover_end <= 0:
        return None
    tail = low[handover_end:]
    target_unavailable = any(
        p in tail
        for p in (
            "специалист сейчас с клиент",
            "мастер сейчас с клиент",
            "мастер-приёмщик сейчас с клиент",
            "мастер-приемщик сейчас с клиент",
            "специалист занят",
            "мастер занят",
        )
    )
    callback_only = (
        any(p in tail for p in ("передам", "передать"))
        and "перезвон" in tail
    ) or (
        "контактный номер" in tail and "перезвон" in tail
    )
    if not (target_unavailable or callback_only):
        return None
    if _extract_staff_name_after_last_handover(ft):
        return None
    return salon_admin


def _is_client_vocative_not_staff_intro(full_text: str, match_start: int, name: str) -> bool:
    """Имя в обращении к клиенту без якоря сотрудника рядом."""
    parts = (name or "").strip().split()
    if not parts:
        return False
    fn = parts[0].lower()
    if _skip_op_firstname_as_client_patronymic_greeting(full_text, match_start, fn):
        return True
    if len(parts) == 1 and _skip_op_firstname_as_outbound_client_greeting(
        full_text, match_start, fn
    ):
        return True
    if _skip_firstname_as_alo_vocative_before_busy_managers(
        full_text, match_start, fn
    ):
        return True
    if _skip_firstname_as_alo_client_identity_check(full_text, match_start, fn):
        return True
    if _skip_firstname_as_client_named_before_op_handover(
        full_text, match_start, fn
    ):
        return True
    return False


def _transcript_has_dealer_staff_reception_intro(full_text: str) -> bool:
    """
    Сотрудник дилера ответил на входящий: «Дилерский центр … Меня зовут X, слушаю вас» (11976).
    Достаточно для справочника ОП по имени, даже без темы продажи авто.
    """
    head = (full_text or "")[:420]
    if not head.strip():
        return False
    low = head.lower()
    if not re.search(r"дилерск\w*\s+центр|официальн\w*\s+дилер", low):
        return False
    return bool(
        re.search(r"меня\s+зовут\s+[а-яё]+\s*,?\s*слушаю\s+вас", low, re.I)
    )


def _menya_zovut_is_external_caller_intro(full_text: str, match_end: int) -> bool:
    """«Меня зовут X, компания Мегафон/Авито…» — представился звонящий, не сотрудник дилера."""
    chunk = (full_text or "")[match_end : match_end + 95].lower()
    if not re.search(r"\bкомпан", chunk):
        return False
    if re.search(r"компан\w*\s+(?:викинг|чери|тенет|tenet|chery)", chunk):
        return False
    external = (
        "мегафон",
        "мегаплас",
        "авито",
        "втб",
        "сбер",
        "тинькоф",
        "т банк",
        "т-банк",
        "корпоративн",
        "обратный звонок",
        "физическое лицо",
    )
    return any(x in chunk for x in external)


def _menya_zovut_is_client_name_before_explicit_op_manager_intro(
    full_text: str, match_start: int, extracted_name: str
) -> bool:
    """
    Клиент может представиться раньше менеджера: «Меня зовут Антон ... Андрей, менеджер ОП».
    В таком случае первое «меня зовут ...» не относится к сотруднику.
    """
    text = full_text or ""
    said_parts = (extracted_name or "").strip().split()
    if not text or not said_parts:
        return False
    said_low = said_parts[0].lower()
    tail = text[match_start : match_start + 900]
    for pat in (
        r"\b([А-ЯЁ][а-яё]{2,20})\s*,\s*менеджер\s+отдела\s+продаж\b",
        r"\b(?:это|что)\s+([А-ЯЁ][а-яё]{2,20})\s*,?\s*менеджер\s+отдела\s+продаж\b",
    ):
        m = re.search(pat, tail, flags=re.IGNORECASE)
        if not m:
            continue
        mgr_low = (m.group(1) or "").strip().lower()
        if mgr_low and mgr_low != said_low:
            return True
    return False


