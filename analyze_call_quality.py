def _intro_roster_rows_for_department(
    department: Optional[str], full_text: str
) -> List[dict]:
    """
    Справочники для имени из фразы представления:
    ОП → только OP_MANAGERS, СТО → только STO_MANAGERS.
    Для прочих/неопределённых отделов справочники не используем:
    имя берём только из явного самопредставления без резолва по roster.
    """
    try:
        from admin_panel.managers_config import OP_MANAGERS, STO_MANAGERS
    except ImportError:
        return []

    if department == "OP":
        return list(OP_MANAGERS)
    if department == "STO":
        return list(STO_MANAGERS)
    if department in (None, "OTHER"):
        if _transcript_has_op_sales_signals_for_manager_roster(full_text):
            return list(OP_MANAGERS)
        if _transcript_has_dealer_staff_reception_intro(full_text):
            if _transcript_is_insurance_body_reception_not_op_sales(full_text):
                if _transcript_has_sto_service_signals_for_manager_roster(full_text):
                    return list(STO_MANAGERS)
                return []
            return list(OP_MANAGERS)
        if _transcript_has_sto_service_signals_for_manager_roster(full_text):
            return list(STO_MANAGERS)
    return []


def _displays_matching_intro_firstname(rows: List[dict], token_lower: str) -> List[str]:
    """Display «Фамилия Имя» (или односложное из справочника), если второе слово = имя-кандидат."""
    tok = _normalize_token_for_sto_firstname_match(token_lower)
    found: List[str] = []
    for m in rows:
        disp = ((m.get("display") or m.get("manager_name")) or "").strip()
        mn = ((m.get("manager_name") or "")).strip()
        if not disp:
            continue
        ps = disp.split()
        if len(ps) >= 2:
            if ps[1].lower() == tok:
                found.append(disp)
        else:
            dl = disp.lower()
            if dl == tok or mn.lower() == tok:
                found.append(disp)
    return list(dict.fromkeys(found))


def _resolve_intro_firstname_via_roster(
    token_lower: str,
    department: Optional[str],
    full_text: str,
    *,
    intro_context: bool,
) -> Optional[str]:
    """
    Одно имя из явного представления → одна строка в справочнике соответствующего отдела (или объединённом наборе).
    Несколько людей с тем же именем в справочнике → None (нужна фамилия или другие правила).
    """
    if not intro_context or not token_lower:
        return None
    rows = _intro_roster_rows_for_department(department, full_text)
    if not rows:
        return None
    matches = _displays_matching_intro_firstname(rows, token_lower)
    if len(matches) == 1:
        return matches[0]
    return None


def _check_manager_name(
    full_text: str,
    name: str,
    pos: int,
    low: str,
    search_low: str = None,
    *,
    intro_context: bool = False,
    department: Optional[str] = None,
) -> Optional[str]:
    """Проверка кандидата в имя менеджера: блоклист, администратор, известные ФИО."""
    exclude_words = [
        "менеджер", "отдела", "продаж", "здравствуйте", "добрый", "день", "вечер", "утро", "зовут",
        "перезванивал", "перезвонил", "перезвонила",
    ]
    if not name or len(name) < 3:
        return None
    name_lower = name.lower()
    if _is_dealer_brand_location_not_person_name(name):
        return None
    if any(exc in name_lower for exc in exclude_words):
        return None
    parts = name_lower.split()
    if name_lower in NON_NAMES_BLOCKLIST or any(p in NON_NAMES_BLOCKLIST for p in parts):
        return None
    if _is_stt_junk_manager_name_candidate(name):
        return None
    if intro_context:
        if not _is_valid_manager_name_from_catalog(name):
            return None
    elif not _is_plausible_manager_name(name, strict=False):
        return None
    if _name_from_administrator_phrase(full_text, pos, name):
        return None
    ctx = search_low if search_low else low
    if intro_context and len(parts) == 1:
        rd = _resolve_intro_firstname_via_roster(
            parts[0], department, full_text, intro_context=True
        )
        if rd:
            return rd
    if re.search(r"\bзахаров\s+илья\b|\bилья\s+захаров\b", name_lower) or (
        name_lower == "илья" and "захаров" in ctx
    ):
        return "Захаров Илья"
    if "щеголев" in name_lower and "андрей" in name_lower:
        return "Щеголев Андрей"
    if "калаев" in name_lower and "андрей" in name_lower:
        return "Калаев Андрей"
    if ("краснощекова" in name_lower or "краснощёкова" in name_lower) and "анастасия" in name_lower:
        return "Краснощекова Анастасия"
    if "краснощук" in name_lower and "анастасия" in name_lower:
        return "Краснощекова Анастасия"
    if "краснощуков" in name_lower and "анастасия" in name_lower:
        return "Краснощекова Анастасия"
    if "краснощекова" in name_lower or "краснощёкова" in name_lower:
        return "Краснощекова Анастасия"
    if len(parts) == 1:
        return _firstname_only_display(_nom_firstname_low(parts[0]))
    return name.title()


def _fuzzy_nearest_manager_display(n: str, department: Optional[str]) -> Optional[str]:
    """
    STT искажает ФИО; выбираем ближайший display из справочника ОП/СТО по similarity всей строки
    (оба порядка: «Фамилия Имя» и «Имя Фамилия»).
    Возвращает строку для сохранения в формате «Имя Фамилия» или None.
    """
    parts = [p for p in (n or "").strip().split() if p]
    if len(parts) < 2:
        return None
    nl = " ".join(parts).lower()
    try:
        from admin_panel.managers_config import OP_MANAGERS, STO_MANAGERS

        if department == "OP":
            rows = OP_MANAGERS
        elif department == "STO":
            rows = STO_MANAGERS
        else:
            rows = list(OP_MANAGERS) + list(STO_MANAGERS)
    except ImportError:
        return None

    def out_from_disp(disp: str) -> str:
        ps = [x for x in disp.strip().split() if x]
        if len(ps) >= 2:
            return f"{ps[1]} {ps[0]}"
        return disp.strip()

    best_ratio = 0.0
    best_disp: Optional[str] = None
    for m in rows:
        disp = ((m.get("display") or m.get("manager_name")) or "").strip()
        if not disp:
            continue
        ps = disp.split()
        variants = [disp.lower()]
        if len(ps) >= 2:
            variants.append(f"{ps[1]} {ps[0]}".lower())
        for v in variants:
            r = SequenceMatcher(None, nl, v).ratio()
            if r > best_ratio:
                best_ratio = r
                best_disp = disp
    if best_disp is None or best_ratio < 0.65:
        return None
    return out_from_disp(best_disp)


def _canonicalize_manager_display(
    name: Optional[str], department: Optional[str] = None
) -> Optional[str]:
    """Приводит к канону из managers_config в формате «Имя Фамилия»."""
    def _to_name_surname(s: str) -> str:
        parts = [p for p in s.strip().split() if p]
        if len(parts) >= 2:
            return f"{parts[1]} {parts[0]}"
        return s.strip()

    if not name:
        return None
    n = name.strip()
    try:
        from admin_panel.managers_config import OP_MANAGERS, STO_MANAGERS

        if department == "OP":
            rows = OP_MANAGERS
        elif department == "STO":
            rows = STO_MANAGERS
        else:
            rows = list(OP_MANAGERS) + list(STO_MANAGERS)
    except ImportError:
        return n
    nl = n.lower()
    for m in rows:
        mn = (m.get("manager_name") or "").strip()
        disp = (m.get("display") or mn).strip()
        if mn.lower() == nl:
            return _to_name_surname(disp)
        if disp.lower() == nl:
            return _to_name_surname(disp)
    fz = _fuzzy_nearest_manager_display(n, department)
    if fz:
        return fz
    return n


def _require_canonical_manager_display(
    name: Optional[str], department: Optional[str] = None
) -> Optional[str]:
    """
    Приводит к канону для сохранения:
    - при совпадении сотрудника из справочника -> «Имя Фамилия»;
    - если есть только имя (без фамилии) -> сохраняем имя.
    """
    def _to_name_surname(s: str) -> str:
        parts = [p for p in s.strip().split() if p]
        if len(parts) >= 2:
            return f"{parts[1]} {parts[0]}"
        return s.strip()

    if not name or not str(name).strip():
        return None
    n = name.strip()
    try:
        from admin_panel.managers_config import OP_MANAGERS, STO_MANAGERS

        if department == "OP":
            rows = OP_MANAGERS
        elif department == "STO":
            rows = STO_MANAGERS
        else:
            rows = list(OP_MANAGERS) + list(STO_MANAGERS)
    except ImportError:
        return n
    nl = n.lower()
    # Точное совпадение по каноническому display/ключу -> «Имя Фамилия».
    for m in rows:
        mn = ((m.get("manager_name") or "")).strip()
        disp = ((m.get("display") or m["manager_name"]) or "").strip()
        if disp and disp.lower() == nl:
            return _to_name_surname(disp)
        if mn and mn.lower() == nl:
            return _to_name_surname(disp)
    fz = _fuzzy_nearest_manager_display(n, department)
    if fz:
        return fz
    # Fallback: если без фамилии распознано только имя из справочника.
    by_first: Dict[str, set] = {}
    for m in rows:
        disp = ((m.get("display") or m["manager_name"]) or "").strip()
        if not disp:
            continue
        parts = [p for p in disp.split() if p]
        if len(parts) < 2:
            continue
        first = parts[1].lower()
        by_first.setdefault(first, set()).add(disp.lower())
    if nl in by_first:
        return n.title()
    return n.title()


def _skip_op_firstname_as_outbound_client_greeting(
    full_text: str, match_start: int, firstname_lower: str
) -> bool:
    """
    Исходящий ОП: «Илья, добрый день. Это Анастасия, автосалон…» — первое имя это клиент,
    не менеджер с уникальным именем «Илья» в справочнике.
    """
    if match_start > 360:
        return False
    low = (full_text or "").lower()
    ctx = low[max(0, match_start - 35) : match_start + 95]
    if not re.search(
        r"\b" + re.escape(firstname_lower) + r"\s*,\s*(?:добрый\s+день|добрый\s+вечер|здравствуйте)\b",
        ctx,
    ):
        return False
    tail = low[match_start:]
    if re.search(
        r"\b(?:это|что)\s+(анастасия|илья|евгений|анастасию|евгения)\b", tail[:750]
    ):
        return True
    if re.search(
        r"\b(?:это|что)\s+[а-яё]{3,}\b(?:\s*,\s*|\s+)(?:автосалон|дилерск|викинги)",
        tail[:750],
    ):
        return True
    # «Андрей, добрый вечер. Меня зовут Анастасия, менеджер…» — первое имя клиент
    if re.search(
        r"\bменя\s+зовут\s+[а-яё]{3,}(?:\s*[,.])?\s*менеджер",
        tail[:900],
        re.I,
    ):
        return True
    if re.search(
        r"\bменя\s+зовут\s+(?:анастасия|илья|евгений|павел|роман|анастасию|евгения)\b",
        tail[:900],
        re.I,
    ):
        return True
    return False


