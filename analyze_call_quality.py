def transcribe_audio(
    file_path: Path,
    model: WhisperModel,
    initial_prompt_override: Optional[str] = None,
    vad_filter: bool = True,
    no_speech_threshold: float = 0.6,
    no_initial_prompt: bool = False,
    apply_domain_normalization: bool = True,
) -> Tuple[str, List[Dict], str]:
    """Транскрибация через faster-whisper large-v3.
    apply_domain_normalization=False — без normalize_transcript (сырой вывод STT для сравнения).
    """
    if not file_path.exists():
        raise FileNotFoundError(f"Файл не найден: {file_path}")

    info = sf.info(str(file_path))
    duration_sec = info.duration
    mins = int(duration_sec // 60)
    secs = int(duration_sec % 60)
    print(f"  📂 Длительность: {mins} мин {secs} с", flush=True)

    if no_initial_prompt:
        prompt = None  # не подставлять шаблон в начало (для СТО — реальное приветствие ассистента)
    else:
        prompt = initial_prompt_override if initial_prompt_override else (INITIAL_PROMPT if WHISPER_USE_INITIAL_PROMPT else None)
    import time
    t0 = time.perf_counter()
    print(f"  📝 Транскрибация {file_path.name}...", flush=True)

    segments, _ = model.transcribe(
        str(file_path),
        language="ru",
        beam_size=WHISPER_BEAM_SIZE,
        temperature=[0.0, 0.2, 0.4],
        vad_filter=vad_filter,
        word_timestamps=False,
        initial_prompt=prompt,
        condition_on_previous_text=False,
        no_speech_threshold=no_speech_threshold,
        compression_ratio_threshold=2.0,
        log_prob_threshold=-0.5,
    )

    pieces: List[str] = []
    segments_with_timestamps: List[Dict] = []
    for seg in segments:
        txt_raw = (seg.text or "").strip()
        if not txt_raw:
            continue
        avg_logprob = getattr(seg, "avg_logprob", None)
        no_speech_prob = getattr(seg, "no_speech_prob", None)
        if avg_logprob is not None and avg_logprob < WHISPER_LOG_PROB_THRESHOLD:
            continue  # низкая уверенность — вероятная галлюцинация
        if no_speech_prob is not None and no_speech_prob > WHISPER_NO_SPEECH_PROB_THRESHOLD:
            continue  # модель считает, что речи нет — не включать в транскрипт
        txt_out = normalize_transcript(txt_raw) if apply_domain_normalization else txt_raw
        pieces.append(txt_out)
        segments_with_timestamps.append({"start": seg.start, "end": seg.end, "text": txt_out})

    raw_text = " ".join(pieces).strip()
    normalized = normalize_transcript(raw_text) if apply_domain_normalization else raw_text
    elapsed = time.perf_counter() - t0
    print(f"  ⏱ Транскрибация заняла {elapsed:.1f} с", flush=True)
    return normalized, segments_with_timestamps, raw_text


def _normalize_token_for_chunk_overlap(tok: str) -> str:
    """Пунктуация и разговорные варианты — только для сравнения на стыке GigaAM-чанков (текст не меняется)."""
    t = tok.strip().lower()
    while len(t) > 1 and t[-1] in ",.!?;:…\"')»":
        t = t[:-1]
    while len(t) > 1 and t[0] in "«\"'(":
        t = t[1:]
    if not t:
        return ""
    equiv = {
        "чё": "что",
        "че": "что",
        "чёто": "что",
        "чото": "что",
        "чето": "что",
        "что-то": "что",
        "чтото": "что",
    }
    if t in equiv:
        return equiv[t]
    if "нет-нет" in t:
        t = t.replace("нет-нет", "нетнет")
    if t == "да-да" or t == "дада":
        return "дада"
    return t


_GIGAAM_COMBO_MODEL_CACHE: Dict[str, object] = {}


def _dedup_join_texts(left: str, right: str, max_overlap_words: int = 16) -> str:
    """Склейка двух кусков по словам с удалением дублей на стыке."""
    left = (left or "").strip()
    right = (right or "").strip()
    if not left:
        return right
    if not right:
        return left

    left_words = left.split()
    right_words = right.split()
    if not left_words or not right_words:
        return f"{left} {right}".strip()

    left_key = [_normalize_token_for_chunk_overlap(w) for w in left_words]
    right_key = [_normalize_token_for_chunk_overlap(w) for w in right_words]
    max_n = min(max_overlap_words, len(left_words), len(right_words))
    trim = 0
    for n in range(max_n, 0, -1):
        if left_key[-n:] == right_key[:n]:
            trim = n
            break
    return " ".join(left_words + right_words[trim:]).strip()


def _load_cached_gigaam_model(path: Path) -> object:
    key = str(Path(path))
    model = _GIGAAM_COMBO_MODEL_CACHE.get(key)
    if model is None:
        model = load_gigaam_model_from_path(Path(path))
        _GIGAAM_COMBO_MODEL_CACHE[key] = model
    return model


def _maybe_combo_transcribe_gigaam(
    file_path: Path,
    normalize_with_llm: bool,
    apply_domain_normalization: bool,
) -> Optional[Tuple[str, List[Dict], str]]:
    """
    Комбо-режим:
    - CTC на первых N секундах,
    - RNNT с (N - overlap) сек,
    - дедуп по словам на стыке.
    При любой ошибке возвращает None (fallback на текущий пайплайн).
    """
    # По умолчанию off: COMBO теряет приветствие после гудков перевода (см. GIGAAM_COMBO_ENABLED в .env).
    enabled = os.environ.get("GIGAAM_COMBO_ENABLED", "0").strip().lower() in ("1", "true", "yes", "y", "on")
    if not enabled:
        return None

    split_sec = float(os.environ.get("GIGAAM_COMBO_SPLIT_SEC", "5.0"))
    overlap_sec = float(os.environ.get("GIGAAM_COMBO_OVERLAP_SEC", "1.0"))
    max_dedup_words = max(1, int(os.environ.get("GIGAAM_COMBO_DEDUP_WORDS", "16")))
    ctc_warmup = float(os.environ.get("GIGAAM_COMBO_CTC_WARMUP_SEC", "0.3"))
    rnnt_warmup = float(os.environ.get("GIGAAM_COMBO_RNNT_WARMUP_SEC", "0.0"))
    combo_first_chunk_sec = float(os.environ.get("GIGAAM_COMBO_FIRST_CHUNK_SEC", "6.0"))
    combo_chunk_overlap_sec = float(os.environ.get("GIGAAM_COMBO_CHUNK_OVERLAP_SEC", "1.0"))
    ctc_path = Path(os.environ.get("GIGAAM_COMBO_CTC_PATH", "models/gigaam-v3"))
    rnnt_path = Path(os.environ.get("GIGAAM_COMBO_RNNT_PATH", "models/gigaam-v3-e2e_rnnt"))

    if split_sec <= 0 or overlap_sec < 0 or overlap_sec >= split_sec:
        return None

    try:
        import tempfile

        audio, sr = sf.read(str(file_path))
        if audio.ndim == 2 and audio.shape[1] >= 2:
            audio = (audio[:, 0].astype(float) + audio[:, 1].astype(float)) / 2.0
        elif audio.ndim > 1:
            audio = audio[:, 0]
        audio = np.asarray(audio, dtype=np.float32)
        duration_sec = len(audio) / float(sr)
        if duration_sec < (split_sec + 1.0):
            return None

        ctc_end_sec = min(split_sec, duration_sec)
        rnnt_start_sec = max(0.0, ctc_end_sec - overlap_sec)
        ctc_end_sample = int(ctc_end_sec * sr)
        rnnt_start_sample = int(rnnt_start_sec * sr)
        ctc_audio = audio[:ctc_end_sample]
        rnnt_audio = audio[rnnt_start_sample:]

        if len(ctc_audio) < int(0.8 * sr) or len(rnnt_audio) < int(2.0 * sr):
            return None

        print(
            f"  🔀 COMBO STT: CTC 0–{ctc_end_sec:.1f}s, RNNT с {rnnt_start_sec:.1f}s (overlap {overlap_sec:.1f}s)",
            flush=True,
        )

        fd1, p1 = tempfile.mkstemp(suffix=".wav")
        fd2, p2 = tempfile.mkstemp(suffix=".wav")
        os.close(fd1)
        os.close(fd2)
        sf.write(p1, ctc_audio, sr)
        sf.write(p2, rnnt_audio, sr)

        prev_warmup = os.environ.get("GIGAAM_WARMUP_SEC")
        prev_first_chunk = os.environ.get("GIGAAM_CHUNK_FIRST_SEC")
        prev_chunk_overlap = os.environ.get("GIGAAM_CHUNK_OVERLAP_SEC")
        try:
            ctc_model = _load_cached_gigaam_model(ctc_path)
            rnnt_model = _load_cached_gigaam_model(rnnt_path)
            os.environ["GIGAAM_CHUNK_FIRST_SEC"] = str(combo_first_chunk_sec)
            os.environ["GIGAAM_CHUNK_OVERLAP_SEC"] = str(combo_chunk_overlap_sec)

            os.environ["GIGAAM_WARMUP_SEC"] = str(ctc_warmup)
            n1, s1, r1 = transcribe_audio_gigaam(
                Path(p1),
                ctc_model,
                normalize_with_llm=normalize_with_llm,
                apply_domain_normalization=apply_domain_normalization,
                _allow_transfer_split=False,
                _allow_combo=False,
            )

            os.environ["GIGAAM_WARMUP_SEC"] = str(rnnt_warmup)
            n2, s2, r2 = transcribe_audio_gigaam(
                Path(p2),
                rnnt_model,
                normalize_with_llm=normalize_with_llm,
                apply_domain_normalization=apply_domain_normalization,
                _allow_transfer_split=False,
                _allow_combo=False,
            )
        finally:
            if prev_warmup is None:
                os.environ.pop("GIGAAM_WARMUP_SEC", None)
            else:
                os.environ["GIGAAM_WARMUP_SEC"] = prev_warmup
            if prev_first_chunk is None:
                os.environ.pop("GIGAAM_CHUNK_FIRST_SEC", None)
            else:
                os.environ["GIGAAM_CHUNK_FIRST_SEC"] = prev_first_chunk
            if prev_chunk_overlap is None:
                os.environ.pop("GIGAAM_CHUNK_OVERLAP_SEC", None)
            else:
                os.environ["GIGAAM_CHUNK_OVERLAP_SEC"] = prev_chunk_overlap
            try:
                Path(p1).unlink(missing_ok=True)
            except Exception:
                pass
            try:
                Path(p2).unlink(missing_ok=True)
            except Exception:
                pass

        combo_norm = _dedup_join_texts(n1, n2, max_overlap_words=max_dedup_words)
        combo_raw = _dedup_join_texts(r1, r2, max_overlap_words=max_dedup_words)

        for seg in (s2 or []):
            seg["start"] = float(seg.get("start", 0.0)) + rnnt_start_sec
            seg["end"] = float(seg.get("end", 0.0)) + rnnt_start_sec
        merged_segments = (s1 or []) + (s2 or [])
        return combo_norm, merged_segments, combo_raw
    except Exception as e:
        print(f"  ⚠️  COMBO STT отключен (fallback на текущий пайплайн): {e}", flush=True)
        return None


def transcribe_audio_gigaam(
    file_path: Path,
    model,
    normalize_with_llm: bool = True,
    apply_domain_normalization: bool = True,
    _allow_transfer_split: bool = True,
    _allow_combo: bool = True,
) -> Tuple[str, List[Dict], str]:
    """
    Транскрибация через GigaAM-v3 (ai-sage/GigaAM-v3).
    Стерео: по умолчанию (L+R)/2; если один канал слабый — только громкий.
    normalize_with_llm=False — только нормализация по правилам (без LLM).
    apply_domain_normalization=False — без normalize_text / normalize_transcript (сырой STT для сравнения).
    """
    if not file_path.exists():
        raise FileNotFoundError(f"Файл не найден: {file_path}")

    import tempfile
    import time

    if _allow_combo:
        combo_res = _maybe_combo_transcribe_gigaam(
            file_path,
            normalize_with_llm=normalize_with_llm,
            apply_domain_normalization=apply_domain_normalization,
        )
        if combo_res is not None:
            return combo_res

    info = sf.info(str(file_path))
    duration_sec = info.duration
    mins = int(duration_sec // 60)
    secs = int(duration_sec % 60)
    print(f"  📂 Длительность: {mins} мин {secs} с", flush=True)

    audio, sr = sf.read(str(file_path))
    was_stereo = audio.ndim == 2 and audio.shape[1] >= 2
    if was_stereo:
        # Всегда (L+R)/2: выбор «только громкий канал» при ratio<0.15 терял тихую сторону
        # (админ/перевод на сервис) и ломал классификацию; микс стабильнее для аналитики.
        audio = (audio[:, 0].astype(float) + audio[:, 1].astype(float)) / 2.0
        print(f"  🔊 Стерео → моно (L+R)/2", flush=True)
    elif audio.ndim > 1:
        audio = audio[:, 0]

    # По умолчанию off: разрез по гудкам даёт второй проход STT без стабильного старта фразы после линии.
    split_on_tones = (
        os.environ.get("GIGAAM_SPLIT_ON_TRANSFER_TONES", "0").strip().lower()
        in ("1", "true", "yes", "y", "on")
    )
    if _allow_transfer_split and split_on_tones:
        split_min_d = float(os.environ.get("GIGAAM_SPLIT_TONE_MIN_DURATION_SEC", "0.6"))
        tone_regions = _detect_dial_tone_regions_mono(audio, sr, min_duration_sec=split_min_d)
        split_sec = _find_transfer_split_sec(tone_regions, sr, duration_sec)
        if split_sec > 0:
            split_sample = int(split_sec * sr)
            if 0 < split_sample < len(audio):
                first = np.asarray(audio[:split_sample], dtype=np.float32)
                second = np.asarray(audio[split_sample:], dtype=np.float32)
                if len(first) > int(2.0 * sr) and len(second) > int(2.0 * sr):
                    print(
                        f"  ✂️  Разрез по гудкам перевода: {split_sec:.1f} с (2 прохода STT)",
                        flush=True,
                    )
                    fd1, p1 = tempfile.mkstemp(suffix=".wav")
                    fd2, p2 = tempfile.mkstemp(suffix=".wav")
                    os.close(fd1)
                    os.close(fd2)
                    sf.write(p1, first, sr)
                    sf.write(p2, second, sr)
                    try:
                        n1, s1, r1 = transcribe_audio_gigaam(
                            Path(p1),
                            model,
                            normalize_with_llm=normalize_with_llm,
                            apply_domain_normalization=apply_domain_normalization,
                            _allow_transfer_split=False,
                            _allow_combo=False,
                        )
                        n2, s2, r2 = transcribe_audio_gigaam(
                            Path(p2),
                            model,
                            normalize_with_llm=normalize_with_llm,
                            apply_domain_normalization=apply_domain_normalization,
                            _allow_transfer_split=False,
                            _allow_combo=False,
                        )
                    finally:
                        try:
                            Path(p1).unlink(missing_ok=True)
                        except Exception:
                            pass
                        try:
                            Path(p2).unlink(missing_ok=True)
                        except Exception:
                            pass
                    # Таймкоды второй части переводим в шкалу исходного файла.
                    for seg in s2:
                        seg["start"] = float(seg.get("start", 0.0)) + split_sec
                        seg["end"] = float(seg.get("end", 0.0)) + split_sec
                    merged_segments = (s1 or []) + (s2 or [])
                    merged_raw = " ".join(x for x in [r1, r2] if x).strip()
                    merged_norm = " ".join(x for x in [n1, n2] if x).strip()
                    return merged_norm, merged_segments, merged_raw

    # По всей длине: участки с узкополосным тоном (гудки перевода) → нули, чтобы не ломать STT. Вкл.: GIGAAM_STRIP_TRANSFER_TONES=1
    strip_tone_enabled = os.environ.get("GIGAAM_STRIP_TRANSFER_TONES", "").strip().lower() in (
        "1",
        "true",
        "yes",
        "y",
        "on",
    )
    tone_stripped_sec = 0.0
    if strip_tone_enabled:
        min_tone_d = float(os.environ.get("GIGAAM_TONE_MIN_DURATION_SEC", "0.15"))
        max_tone_f = float(os.environ.get("GIGAAM_TONE_STRIP_MAX_FRAC", "0.42"))
        audio, tone_stripped_sec = strip_dial_tone_regions_mono(
            audio, sr, min_duration_sec=min_tone_d, max_stripped_frac=max_tone_f
        )
        if tone_stripped_sec > 0:
            print(
                f"  🔇 Участки гудков заменены тишиной: ~{tone_stripped_sec:.1f} с",
                flush=True,
            )

    # Прогрев: префикс тишины в начале (по умолчанию 1 с) — лучше распознавание старта фразы; env GIGAAM_WARMUP_SEC=0 отключает
    GIGAAM_WARMUP_SEC = float(os.environ.get("GIGAAM_WARMUP_SEC", "1.0"))
    if GIGAAM_WARMUP_SEC > 0:
        n_silence = int(GIGAAM_WARMUP_SEC * sr)
        silence = np.zeros(n_silence, dtype=audio.dtype)
        audio = np.concatenate([silence, audio])
        print(f"  🔇 Прогрев: {GIGAAM_WARMUP_SEC:.1f} с тишины в начале", flush=True)

    t0 = time.perf_counter()
    print(f"  📝 GigaAM-v3 (e2e_ctc): транскрибация {file_path.name}...", flush=True)

    GIGAAM_LONGFORM_THRESHOLD_SEC = 25.0
    CHUNK_DURATION_SEC = 20.0
    # Первый чанк длиннее следующих — старт фразы целиком; переопределение: GIGAAM_CHUNK_FIRST_SEC
    CHUNK_FIRST_DURATION_SEC = float(os.environ.get("GIGAAM_CHUNK_FIRST_SEC", "8.0"))
    # Перекрытие чанков: меньше — короче зона двойного распознавания; дефолт 2 с (пайплайн). Env: GIGAAM_CHUNK_OVERLAP_SEC
    _ov_env = float(os.environ.get("GIGAAM_CHUNK_OVERLAP_SEC", "2.0"))
    chunk_overlap_sec = max(
        0.5,
        min(_ov_env, CHUNK_FIRST_DURATION_SEC - 0.25, CHUNK_DURATION_SEC - 1.0),
    )
    # Стык чанков: дедуп по словам + нормализация токенов (_normalize_token_for_chunk_overlap). Env: GIGAAM_CHUNK_DEDUP_WORDS
    chunk_dedup_words = max(1, int(os.environ.get("GIGAAM_CHUNK_DEDUP_WORDS", "12")))
    try:
        if duration_sec <= GIGAAM_LONGFORM_THRESHOLD_SEC:
            transcribe_path = file_path
            if was_stereo or GIGAAM_WARMUP_SEC > 0 or strip_tone_enabled:
                fd, p = tempfile.mkstemp(suffix=".wav")
                os.close(fd)
                sf.write(p, audio, sr)
                transcribe_path = Path(p)
            try:
                transcription = model.transcribe(str(transcribe_path))
                raw_text = (transcription or "").strip()
            finally:
                if transcribe_path != file_path and transcribe_path.exists():
                    try:
                        transcribe_path.unlink()
                    except Exception:
                        pass
            segments_with_timestamps = [{"start": 0.0, "end": duration_sec, "text": raw_text}]
        else:
            # Чанки с перекрытием
            print(
                f"  📐 GigaAM чанки: {CHUNK_DURATION_SEC:.0f} с (первый {CHUNK_FIRST_DURATION_SEC:.0f} с), "
                f"overlap {chunk_overlap_sec:.1f} с, дедуп до {chunk_dedup_words} слов",
                flush=True,
            )
            pieces = []
            segments_with_timestamps = []
            step_sec = CHUNK_DURATION_SEC - chunk_overlap_sec
            n_samples_first = int(CHUNK_FIRST_DURATION_SEC * sr)
            n_samples_chunk = int(CHUNK_DURATION_SEC * sr)
            n_samples_step = int(step_sec * sr)
            n_samples_overlap = int(chunk_overlap_sec * sr)

            def _trim_overlap(prev_txt: str, curr_txt: str) -> str:
                """Убирает повторы на границе чанков (первые слова curr совпадают с концом prev)."""
                if not prev_txt or not curr_txt:
                    return curr_txt
                prev_words = prev_txt.split()
                curr_words = curr_txt.split()
                prev_key = [_normalize_token_for_chunk_overlap(w) for w in prev_words]
                curr_key = [_normalize_token_for_chunk_overlap(w) for w in curr_words]
                max_overlap = min(chunk_dedup_words, len(prev_words), len(curr_words))
                for n in range(max_overlap, 0, -1):
                    if prev_key[-n:] == curr_key[:n]:
                        return " ".join(curr_words[n:])
                return curr_txt

            duration_padded_sec = len(audio) / sr
            with tempfile.TemporaryDirectory(prefix="gigaam_chunks_") as tmpdir:
                pos = 0
                prev_txt = ""
                chunk_size = n_samples_first
                first_chunk = True
                while pos < len(audio):
                    chunk = audio[pos : pos + chunk_size]
                    start_sec = pos / sr
                    end_sec = min((pos + len(chunk)) / sr, duration_padded_sec)
                    chunk_path = Path(tmpdir) / f"chunk_{len(pieces):04d}.wav"
                    sf.write(str(chunk_path), chunk, sr)
                    txt = (model.transcribe(str(chunk_path)) or "").strip()
                    if txt:
                        txt_trimmed = _trim_overlap(prev_txt, txt)
                        prev_txt = txt
                        if txt_trimmed:
                            pieces.append(txt_trimmed)
                            segments_with_timestamps.append({"start": start_sec, "end": end_sec, "text": txt_trimmed})
                    # После первого чанка: не шагать на полный step, если первый короче — иначе пропуск аудио (напр. 8 с vs step 16 с)
                    if first_chunk:
                        advance = min(
                            n_samples_step,
                            max(1, n_samples_first - n_samples_overlap),
                        )
                        pos += advance
                        first_chunk = False
                    else:
                        pos += n_samples_step
                    chunk_size = n_samples_chunk
                    if pos >= len(audio) and len(pieces) == 0:
                        break
            raw_text = " ".join(pieces)
            if apply_domain_normalization:
                for seg in segments_with_timestamps:
                    seg["text"] = normalize_text(seg["text"])
            # Таймкоды чанков в шкале «с прогревом» — переводим в шкалу исходного файла
            if GIGAAM_WARMUP_SEC > 0 and segments_with_timestamps:
                for seg in segments_with_timestamps:
                    seg["start"] = max(0.0, seg["start"] - GIGAAM_WARMUP_SEC)
                    seg["end"] = max(0.0, seg["end"] - GIGAAM_WARMUP_SEC)
                    seg["end"] = min(seg["end"], duration_sec)
    except Exception as e:
        print(f"  ⚠️  GigaAM transcribe error: {e}", flush=True)
        raise

    if not apply_domain_normalization:
        txt_norm = raw_text.strip()
    elif normalize_with_llm:
        txt_norm = normalize_transcript(raw_text)
    else:
        txt_norm = normalize_text(raw_text)
    # Для коротких файлов — один сегмент с нормализованным текстом
    if duration_sec <= GIGAAM_LONGFORM_THRESHOLD_SEC and segments_with_timestamps:
        segments_with_timestamps[0]["text"] = txt_norm
    normalized = txt_norm
    elapsed = time.perf_counter() - t0
    print(f"  ⏱ GigaAM транскрибация заняла {elapsed:.1f} с", flush=True)
    return normalized, segments_with_timestamps, raw_text


def transcribe_audio_alt(
    file_path: Path,
    model: WhisperModel,
    initial_prompt_override: Optional[str] = None,
) -> Tuple[str, List[Dict], str]:
    """Повторная транскрибация с альтернативными параметрами."""
    if not file_path.exists():
        raise FileNotFoundError(f"Файл не найден: {file_path}")
    prompt = initial_prompt_override if initial_prompt_override else (INITIAL_PROMPT if WHISPER_USE_INITIAL_PROMPT else None)
    import time
    t0 = time.perf_counter()
    print(f"  📝 Повторная транскрибация {file_path.name} (альт. режим)...", flush=True)
    segments, _ = model.transcribe(
        str(file_path),
        language="ru",
        beam_size=WHISPER_BEAM_SIZE,
        temperature=[0.0],
        vad_filter=True,
        word_timestamps=False,
        initial_prompt=prompt,
        condition_on_previous_text=False,
        no_speech_threshold=0.6,
        compression_ratio_threshold=2.0,
        log_prob_threshold=-0.5,
    )
    pieces: List[str] = []
    segments_with_timestamps: List[Dict] = []
    for seg in segments:
        txt_raw = (seg.text or "").strip()
        if not txt_raw:
            continue
        avg_logprob = getattr(seg, "avg_logprob", None)
        no_speech_prob = getattr(seg, "no_speech_prob", None)
        if avg_logprob is not None and avg_logprob < WHISPER_LOG_PROB_THRESHOLD:
            continue
        if no_speech_prob is not None and no_speech_prob > WHISPER_NO_SPEECH_PROB_THRESHOLD:
            continue
        txt_norm = normalize_transcript(txt_raw)
        pieces.append(txt_norm)
        segments_with_timestamps.append({"start": seg.start, "end": seg.end, "text": txt_norm})
    raw_text = " ".join(pieces).strip()
    normalized = normalize_transcript(raw_text)
    elapsed = time.perf_counter() - t0
    print(f"  ⏱ Повторная транскрибация заняла {elapsed:.1f} с", flush=True)
    return normalized, segments_with_timestamps, raw_text


def is_degenerate_transcript(text: str) -> bool:
    """
    Эвристика для «плохих» транскрипций:
    - очень короткий текст, почти полностью состоящий из шумовых фраз;
    - или длинный текст с очень малым количеством уникальных слов (циклический бред).
    """
    if not text:
        return True

    low = text.lower()
    # Случай с «звонит мобильный телефон» и аналогичными сообщениями
    if "звонит мобильный телефон" in low and len(low.split()) <= 10:
        return True

    words = [w.strip(".,!?:;\"'()") for w in low.split()]
    words = [w for w in words if w]
    if not words:
        return True

    unique_words = set(words)
    # Если текст длинный, а уникальных слов очень мало — считаем транскрипцию зацикленной
    if len(words) >= 30 and len(unique_words) <= 5:
        return True

    return False


def filter_noise_segments(segments: List[Dict]) -> List[Dict]:
    """Удаляет сегменты, содержащие шумовые фразы (гудки и т.п.)."""
    cleaned: List[Dict] = []
    for seg in segments:
        txt = (seg.get("text") or "").strip()
        if not txt:
            continue
        low = txt.lower()
        if any(phrase in low for phrase in NOISE_PHRASES):
            continue
        cleaned.append(seg)
    return cleaned


# Паттерны галлюцинированных ролей в начале сегмента (Whisper иногда вставляет их в текст)
HALLUCINATED_ROLE_PREFIXES = (
    "менеджер ",
    "менедже ",
    "клиент ",
    "администратор ",
)


def postprocess_hallucination_segments(segments: List[Dict]) -> List[Dict]:
    """
    Постобработка галлюцинаций Whisper:
    1) Удаляет из текста сегментов вставленные роли (Менеджер, Клиент, Администратор);
    2) Сворачивает подряд идущие одинаковые короткие фразы (Окей, до свидания и т.п.) — оставляет макс. 2.
    """
    if not segments:
        return []

    # 1. Убираем префикс роли из каждого сегмента
    cleaned: List[Dict] = []
    for seg in segments:
        txt = (seg.get("text") or "").strip()
        if not txt:
            continue
        low = txt.lower()
        stripped = txt
        for prefix in HALLUCINATED_ROLE_PREFIXES:
            if low.startswith(prefix):
                stripped = txt[len(prefix):].lstrip()
                low = stripped.lower()
                break
        if stripped:
            cleaned.append({**seg, "text": stripped})

    # 2. Сворачиваем повторяющиеся короткие фразы (макс. 2 подряд)
    MAX_CONSECUTIVE_SHORT = 2
    SHORT_PHRASE_WORDS = 4  # фраза считается короткой, если <= 4 слов

    result: List[Dict] = []
    i = 0
    while i < len(cleaned):
        seg = cleaned[i]
        txt = (seg.get("text") or "").strip()
        word_count = len(txt.split()) if txt else 0
        is_short = word_count <= SHORT_PHRASE_WORDS and txt

        if not is_short:
            result.append(seg)
            i += 1
            continue

        # Считаем, сколько подряд идёт такая же фраза
        txt_norm = txt.lower().strip(".,!? ")
        count = 0
        j = i
        while j < len(cleaned):
            other = (cleaned[j].get("text") or "").strip().lower().strip(".,!? ")
            if other == txt_norm:
                count += 1
                j += 1
            else:
                break

        if count <= MAX_CONSECUTIVE_SHORT:
            for k in range(count):
                result.append(cleaned[i + k])
        else:
            # Оставляем только MAX_CONSECUTIVE_SHORT сегментов
            for k in range(MAX_CONSECUTIVE_SHORT):
                result.append(cleaned[i + k])

        i += count

    return result


def normalize_domain_text(text: str) -> str:
    """
    Исправляет типичные ошибки распознавания (бренды, имена, термины).
    Работает поверх сырого текста STT.
    """
    if not text:
        return text
    result = text
    # Специальная правка только для первой фразы:
    # "администратор Д..." -> стандартная витрина дилера.
    result = re.sub(
        r"^\s*(?:[а-яa-z]{1,20}\s+)?администратор\s+д[а-яa-z]{0,12}\b",
        "Официальный дилер Чери Тенет, администратор Диана",
        result,
        flags=re.IGNORECASE,
    )
    result = re.sub(
        r"^\s*сервис\b",
        "Викинги Чери Сервис",
        result,
        flags=re.IGNORECASE,
    )
    for wrong, correct in DOMAIN_REPLACEMENTS.items():
        if len(wrong) == 1:
            pattern = re.compile(r"\b" + re.escape(wrong) + r"\b", flags=re.IGNORECASE)
        else:
            pattern = re.compile(re.escape(wrong), flags=re.IGNORECASE)
        result = pattern.sub(correct, result)
    return result


def cut_hostess_prelude_for_file(
    file_number: int,
    segments_with_timestamps: List[Dict],
    full_transcript: str,
) -> Tuple[List[Dict], str]:
    """
    Для тестовых файлов отрезает вступительную речь хостес и технический пролог (гудки и т.п.).
    Всё от начала до указанных «последних слов хостес» (включительно) или до заданного времени удаляется.
    """
    # Файл 1: полностью диалог с хостес — для аналитики менеджера его убираем целиком
    if file_number == 1:
        return [], ""

    # Файл 3: хостес нет, сразу отвечает менеджер — ничего не обрезаем
    if file_number == 3:
        return segments_with_timestamps, full_transcript

    # Файл 4: до 10 с — гудки, потом разговор менеджера с клиентом; вырезаем только гудки
    if file_number == 4:
        threshold = 10.0
        new_segments = [seg for seg in segments_with_timestamps if seg["end"] > threshold]
        new_full = " ".join((seg["text"] or "").strip() for seg in new_segments if (seg["text"] or "").strip())
        return new_segments, new_full

    # Маркеры последних фраз хостес: всё до конца фразы (включительно) вырезаем.
    markers_by_file = {
        1: [
            # для файла 1 используется полное обрезание выше
        ],
        2: [
            "я вас сейчас переключу на менеджера, оставайтесь на линии.",
            "оставайтесь на линии",
            "8-0-1",
            "8 0 1",
        ],
        5: [
            "хорошо, станислав остаётся на линце для вас отделом продаж.",
            "хорошо, станислав остается на линце для вас отделом продаж.",
            "хорошо, станислав остаётся на линии для вас отделом продаж.",
            "станислав остается на линце для вас отделом продаж",
            "станислав остаётся на линце для вас отделом продаж",
            "на линце для вас отделом продаж",
            "на линии для вас отделом продаж",
            "хорошо, станисов остаётся на линии для вас отделом продаж.",
            "станислав, оставайтесь на линзе, я вас сделаю продаж",
            "станислав, оставайтесь на лини",
        ],
        4: [
            "виктор, выключай автоцентр",
        ],
    }

    markers = markers_by_file.get(file_number)
    if not markers:
        return segments_with_timestamps, full_transcript

    # Нормализуем ё→е, чтобы маркер совпадал и при "остаётся", и при "остается" (файл 5)
    def norm(s: str) -> str:
        return (s or "").lower().replace("ё", "е")
    text_norm = norm(full_transcript)
    cut_pos = -1
    for m in markers:
        m_norm = norm(m)
        idx = text_norm.find(m_norm)
        if idx != -1:
            end_idx = idx + len(m_norm)
            if end_idx > cut_pos:
                cut_pos = end_idx

    if cut_pos == -1:
        # Файл 5: запасной вариант — режем до первой реплики с «телефон»/«номер» (первая фраза после хостес)
        if file_number == 5:
            for idx, seg in enumerate(segments_with_timestamps):
                txt = (seg.get("text") or "").strip().lower()
                if "телефон" in txt or ("номер" in txt and "скажите" in txt):
                    if idx > 0:
                        new_segments = segments_with_timestamps[idx:]
                        new_full = " ".join((s.get("text") or "").strip() for s in new_segments if (s.get("text") or "").strip())
                        print(f"  ✂️  Файл 5: маркер хостес не найден, обрезано по «телефон/номер» (с реплики {idx + 1}), осталось: {len(new_segments)}", flush=True)
                        return new_segments, new_full
                    break
        if file_number in (2, 5):
            snippet = (full_transcript or "")[:350].replace("\n", " ")
            print(f"  ⚠️  Файл {file_number}: маркер хостес не найден. Начало текста: «{snippet}...»", flush=True)
        return segments_with_timestamps, full_transcript

    # Строим соответствие сегментов к позициям символов в полном тексте
    new_segments: List[Dict] = []
    current_pos = 0
    first = True
    for seg in segments_with_timestamps:
        txt = (seg["text"] or "").strip()
        if not txt:
            continue
        start_char = current_pos
        end_char = start_char + len(txt)
        # Следующий сегмент будет отделён пробелом
        current_pos = end_char + 1

        # Пропускаем сегменты, которые целиком попадают в блок хостес
        if end_char <= cut_pos:
            continue

        # Сегменты после cut_pos оставляем без изменений (по времени)
        new_segments.append(seg)

    new_full = full_transcript[cut_pos:].lstrip()
    if file_number in (2, 5):
        print(f"  ✂️  Файл {file_number}: обрезано хостес до маркера, осталось реплик: {len(new_segments)}", flush=True)
    return new_segments, new_full


def perform_diarization(file_path: Path) -> Optional[Dict]:
    """Выполняет диаризацию через pyannote.audio."""
    if Pipeline is None:
        print("  ⚠️  pyannote.audio не установлен, диаризация пропущена", flush=True)
        return None

    hf_token = os.environ.get("HF_TOKEN")
    if not hf_token:
        print("  ⚠️  HF_TOKEN не установлен, диаризация пропущена", flush=True)
        return None

    try:
        import time as _time
        t0_diar = _time.perf_counter()
        print(f"  🎤 Диаризация {file_path.name}...", flush=True)
        
        # Определяем устройство для диаризации
        try:
            import torch
            use_cuda = torch.cuda.is_available()
        except ImportError:
            use_cuda = False
        
        device = torch.device("cuda" if use_cuda else "cpu")
        print(f"  🔧 Диаризация использует устройство: {device}", flush=True)
        
        # Community-1 — лучшая open-source диаризация (шум, телефон); при ошибке — fallback на 3.1
        pipeline = None
        models = ("pyannote/speaker-diarization-community-1", "pyannote/speaker-diarization-3.1")
        last_error = None
        for idx, model_id in enumerate(models):
            try:
                # HF_TOKEN из окружения; pyannote читает его автоматически (не передаём token/use_auth_token)
                os.environ["HF_TOKEN"] = str(hf_token)
                os.environ["HUGGING_FACE_HUB_TOKEN"] = str(hf_token)
                pipeline = Pipeline.from_pretrained(model_id)
                break
            except Exception as e:
                last_error = e
                err_msg = str(e).lower()
                if "plda" in err_msg or "unexpected keyword" in err_msg:
                    if idx + 1 < len(models):
                        print(f"  ⚠️  {model_id} несовместима с версией pyannote, пробуем {models[idx + 1]}...", flush=True)
                    else:
                        print(f"  ⚠️  {model_id}: {e}", flush=True)
                else:
                    print(f"  ⚠️  {model_id}: {e}", flush=True)
        if pipeline is None:
            print("  ⚠️  Диаризация пропущена, роли будут определены по тексту.", flush=True)
            return None
        
        # Перемещаем pipeline на GPU если доступно
        if use_cuda:
            pipeline = pipeline.to(device)
        
        # pyannote принимает путь к файлу (Community-1 требует path, не ndarray)
        diarization = pipeline(str(file_path))
        print(f"  ⏱ Диаризация заняла {_time.perf_counter() - t0_diar:.1f} с", flush=True)
        
        # Преобразуем результат в удобный формат
        speaker_segments = []
        # Проверяем тип результата диаризации
        if hasattr(diarization, 'itertracks'):
            for turn, _, speaker in diarization.itertracks(yield_label=True):
                speaker_segments.append({
                    "start": turn.start,
                    "end": turn.end,
                    "speaker": speaker,
                })
        elif hasattr(diarization, 'get_timeline'):
            # Альтернативный формат результата
            for segment in diarization.get_timeline():
                label = diarization.get_labels(segment)
                if label:
                    speaker_segments.append({
                        "start": segment.start,
                        "end": segment.end,
                        "speaker": list(label)[0] if label else "SPEAKER_00",
                    })
        else:
            # Пробуем напрямую итерироваться
            try:
                for segment in diarization:
                    speaker_segments.append({
                        "start": segment.start,
                        "end": segment.end,
                        "speaker": segment.label if hasattr(segment, 'label') else "SPEAKER_00",
                    })
            except:
                print(f"  ⚠️  Не удалось обработать результат диаризации", flush=True)
                return None
        
        return {"segments": speaker_segments, "sample_rate": sample_rate}
    except Exception as e:
        print(f"  ⚠️  Ошибка диаризации: {e}", flush=True)
        return None


