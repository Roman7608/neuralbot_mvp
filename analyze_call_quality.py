def _is_dealer_brand_location_not_person_name(name: str) -> bool:
    """Бренд/локация дилера в STT — не имя менеджера («Тэнет Тольяттивикинги» и т.п.)."""
    nl = (name or "").strip().lower()
    if not nl:
        return False
    return any(sub in nl for sub in _DEALER_BRAND_LOCATION_NAME_SUBSTR)

