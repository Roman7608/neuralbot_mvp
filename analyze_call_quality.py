def _normalize_op_phrase_text(text: str) -> str:
    low = (text or "").lower().replace("ё", "е")
    low = re.sub(r"[^а-яa-z0-9]+", " ", low)
    return re.sub(r"\s+", " ", low).strip()


def op_has_phrase(text: str, phrases: Tuple[str, ...] | list[str]) -> bool:
    """Подстрока или нормализованное совпадение (устойчиво к пунктуации STT)."""
    low = (text or "").lower()
    norm = _normalize_op_phrase_text(text)
    for phrase in phrases:
        p = (phrase or "").strip().lower()
        if not p:
            continue
        if p in low:
            return True
        if _normalize_op_phrase_text(p) in norm:
            return True
    return False


