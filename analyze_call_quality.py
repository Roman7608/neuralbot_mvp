def apply_auto_manager_for_call(
    call_id: int,
    full_text: str,
    department: Optional[str],
    *,
    existing_row: Optional[Dict[str, Any]] = None,
) -> None:
    """
    Сохраняет авто-извлечённого менеджера. Если извлечь нечего — сбрасывает поле,
    если ранее стоял source=auto или имя было пустым (ручные правки не трогаем).
    """
    try:
        from database.postgresql_manager import CallAnalyticsDB

        mgr = extract_manager_name_from_full_transcript(full_text, department=department)
        if mgr:
            if department == "OP":
                try:
                    from admin_panel.managers_config import canonical_op_manager_for_db

                    mgr = canonical_op_manager_for_db(mgr) or mgr
                except ImportError:
                    pass
            CallAnalyticsDB.set_manager_name(call_id, mgr, source="auto")
            return
        row = existing_row if existing_row is not None else CallAnalyticsDB.get_call_with_details(call_id)
        row = row or {}
        src = (row.get("manager_name_source") or "").strip().lower()
        prev = (row.get("manager_name") or "").strip()
        if src == "auto" or not prev:
            CallAnalyticsDB.set_manager_name(call_id, "", source="auto")
    except Exception:
        pass


def _infer_customer_name_from_repeated_mentions(
    search_low: str,
    *,
    manager_name: Optional[str] = None,
    admin_names: Optional[set[str]] = None,
    min_count: int = 2,
    max_chars: int = 4500,
) -> Optional[str]:
    """
    Имя клиента по частым обращениям менеджера в тексте (≥ min_count),
    если явного ответа на «как обращаться» нет или STT его не распознал.
    """
    mgr_lower = (manager_name or "").lower()
    mgr_tokens = {t for t in re.split(r"\s+", mgr_lower) if len(t) >= 3}
    extra_exclude = admin_names or set()
    brand_like = frozenset({"чери", "черри", "тенет", "тэнет", "тигго", "джили", "китай"})
    tail = (search_low or "")[:max_chars]
    best_k: Optional[str] = None
    best_cnt = 0
    for kn in COMMON_NAMES:
        if len(kn) < 3 or kn in brand_like:
            continue
        if kn in mgr_tokens or kn in extra_exclude:
            continue
        pat = r"(?<![а-яё])(?:%s)(?:а|у|е|ом|ой|и)?(?![а-яё])" % re.escape(kn)
        cnt = len(re.findall(pat, tail, flags=re.IGNORECASE))
        if cnt >= min_count and cnt > best_cnt:
            best_cnt = cnt
            best_k = kn
    if best_k:
        canon = next((n for n in get_canonical_first_names() if n.lower() == best_k), None)
        return canon if canon else best_k.title()
    return None


def extract_customer_name_from_full_transcript(full_text: str, manager_name: Optional[str] = None) -> Optional[str]:
    """Извлекает имя клиента из полной транскрипции.

    С переводом с администратора — только текст после handover; без перевода (менеджер сразу) — с начала.
    Порядок: 1) «X, это Y, менеджер»; 2) ответ на «как обращаться»; 2b) «меня зовут X» (клиент);
    3) «X, добрый день» + «Меня зовут»; 4) «Алло, X?»; 5) «не затягивайте, X»; 6) прочие обращения.
    """
    low = (full_text or "").lower()
    handover = RE_HANDOVER_TO_MANAGER.search(low)
    admin_block_end = handover.start() if handover else None
    admin_names = _collect_admin_staff_names(low, admin_block_end=admin_block_end)
    exclude_names = {"менеджер", "отдела", "продаж", "компания", "дилерский", "центр",
                     "здравствуйте", "добрый", "день", "вечер", "утро", "привет", "алло"}
    if manager_name:
        exclude_names.update(manager_name.lower().split())
    exclude_names.update(admin_names)
    name_fixes = {"вот": "Ольга", "вол": "Ольга", "бильдон": "Бильдан", "бильдан": "Бильдан",
                  "ольга": "Ольга", "ольг": "Ольга", "владислав": "Владислав", "влад": "Владислав",
                  "никита": "Никита", "никит": "Никита", "дмитрий": "Дмитрий", "дмитри": "Дмитрий",
                  "павел": "Павел", "пав": "Павел", "роман": "Роман", "ром": "Роман",
                  "олег": "Алик", "алик": "Алик",
                  "зуслан": "Рустам", "алья": "Илья"}

    def _accept_name(name: str, match_start: int) -> Optional[str]:
        if not name or len(name) < 2:
            return None
        name_lower = name.lower()
        # Справочник COMMON_NAMES без «ё» (Фёдор → федор).
        name_norm = name_lower.replace("ё", "е")
        if name_lower in exclude_names or name_norm in exclude_names:
            return None
        parts = name_lower.split()
        if (
            name_lower in NON_NAMES_BLOCKLIST
            or name_norm in NON_NAMES_BLOCKLIST
            or any(p in NON_NAMES_BLOCKLIST or p.replace("ё", "е") in NON_NAMES_BLOCKLIST for p in parts)
        ):
            return None
        if _name_from_administrator_context(full_text, match_start):
            return None
        if name_lower in admin_names or name_norm in admin_names:
            return None
        if name_lower in name_fixes:
            return name_fixes[name_lower]
        if name_norm in name_fixes:
            return name_fixes[name_norm]
        if name_lower in CLIENT_NON_NAMES or name_norm in CLIENT_NON_NAMES:
            return None
        if name_norm in COMMON_NAMES:
            return name_norm.title()
        for known in COMMON_NAMES:
            if known.startswith(name_norm[:3]) and len(name_norm) >= 3:
                return known.capitalize()
        return None

    # 0) Имя клиента, которое администратор уточнил до перевода на менеджера
    if handover:
        admin_scope = full_text[: handover.start()]
        admin_ask_patterns = (
            r"как\s+(?:могу\s+)?(?:к\s+(?:вам|там|вас)\s+)?(?:могу\s+)?обращаться"
            r"[\s\S]{0,80}?\bменя\s+([А-ЯЁ][а-яё]{2,20})\s+зовут\b",
            r"как\s+вас\s+зовут\s*[?]?\s*[\u2013\u2014\-—:\s]*(?:э[-\s]?э\s+)?([А-ЯЁ][а-яё]{2,20})\b",
            r"как\s+(?:могу\s+)?(?:к\s+(?:вам|там|вас)\s+)?(?:могу\s+)?обращаться\s*[?]?\s*[\u2013\u2014\-—:\s]*(?:э[-\s]?э\s+)?([А-ЯЁ][а-яё]{2,20})\b",
            r"подскаж(?:ите|и),?\s+как\s+(?:могу\s+)?(?:к\s+(?:вам|там|вас)\s+)?обращаться\s*[?]?\s*[\u2013\u2014\-—:\s]*(?:э[-\s]?э\s+)?([А-ЯЁ][а-яё]{2,20})\b",
            # 28536: «Так могу к вас обращаться? Фёдором звать.»
            r"(?:так|как)\s+могу\s+к\s+(?:вам|вас|там)\s+обращаться\s*[?]?\s*[\u2013\u2014\-—:\s]*"
            r"([А-ЯЁ][а-яё]{2,20})ом\s+звать\b",
            r"(?:так|как)\s+могу\s+к\s+(?:вам|вас|там)\s+обращаться\s*[?]?\s*[\u2013\u2014\-—:\s]*"
            r"([А-ЯЁ][а-яё]{2,20})\s+звать\b",
            # 28536: «Фёдор, переведу вас на менеджера…»
            r"(?:так|как)\s+могу\s+к\s+(?:вам|вас|там)\s+обращаться[\s\S]{0,100}?"
            r"\b([А-ЯЁ][а-яё]{2,20})\s*,?\s*перевед",
            r"подскаж(?:ите|и),?\s+(?:так|как)\s+могу\s+к\s+(?:вам|вас|там)\s+обращаться[\s\S]{0,100}?"
            r"\b([А-ЯЁ][а-яё]{2,20})\s*,?\s*перевед",
        )
        for pattern in admin_ask_patterns:
            for m in re.finditer(pattern, admin_scope, flags=re.IGNORECASE):
                name = m.group(1).strip()
                out = _accept_name(name, m.start())
                if out:
                    return out
                if re.search(
                    rf"\b{re.escape(name)}\s*\?\s*(?:да|угу|верно)\b",
                    admin_scope,
                    flags=re.IGNORECASE,
                ):
                    nl = name.lower().replace("ё", "е")
                    if nl not in exclude_names and nl not in NON_NAMES_BLOCKLIST:
                        return name.strip().title()

    search_text = full_text[handover.end():] if handover else full_text
    search_low = search_text.lower()
    search_blocks: list[tuple[str, int]] = [(search_text, handover.end() if handover else 0)]

    # 1) «X, это Y, менеджер» — X клиент
    for block, start_off in search_blocks:
        for m in re.finditer(
            r"([А-ЯЁ][а-яё]+),?\s*это\s+[А-ЯЁ][а-яё]+,?\s*менеджер",
            block, flags=re.IGNORECASE
        ):
            name = m.group(1).strip()
            pos_in_full = start_off + m.start()
            out = _accept_name(name, pos_in_full)
            if out:
                return out

    # 2) Ответ на «как обращаться» / «как зовут»
    _dash = r"\s*[?\s.\u2013\u2014\-—:\s]*"
    ask_patterns = [
        r"(?:как\s+(?:к\s+вам(?:\s+могу)?\s+обращаться|могу\s+к\s+вам\s+обращаться)|как\s+вас?\s+можно\s+называть|как\s+вас\s+зовут|как\s+к\s+вам\s+можно\s+обращаться)" + _dash + r"([А-ЯЁ][а-яё]+)(?:\s+меня\s+зовут)?[.\s]",
        r"(?:как\s+к\s+вам\s+можно\s+обращаться|как\s+к\s+вам\s+могу\s+обращаться|обращаться)\s*[?\s.\u2013\u2014\-—:\s]+([А-ЯЁ][а-яё]+)\s*[.\s]",
        r"как\s+вас\s+зовут\s*[?]?\s*[\u2013\u2014\-—:\s]*([А-ЯЁ][а-яё]+)\b",
        r"(?:к\s+вам\s+по\s+имени\s+как\s+можно\s+обращаться|как\s+вам\s+по\s+имени\s+можно\s+обращаться|как\s+к\s+вам\s+по\s+имени(?:\s+можно\s+обращаться)?)" + _dash + r"([А-ЯЁ][а-яё]+)(?:\s+меня\s+зовут)?[.\s]",
    ]
    for block, start_off in search_blocks:
        for pattern in ask_patterns:
            for m in re.finditer(pattern, block, flags=re.IGNORECASE):
                name = m.group(1).strip()
                out = _accept_name(name, start_off + m.start())
                if out:
                    return out

    # 2b) Клиент сам: «меня зовут X» (не менеджер)
    mgr_tokens = _manager_name_tokens(manager_name)
    for block, start_off in search_blocks:
        for m in re.finditer(
            r"(?<![а-яё])меня\s+зовут\s+([А-ЯЁ][а-яё]{2,20})\b",
            block,
            flags=re.IGNORECASE,
        ):
            if _is_manager_self_intro_tail(block, m.end()):
                continue
            name = m.group(1).strip()
            if name.lower().replace("ё", "е") in mgr_tokens:
                continue
            out = _accept_name(name, start_off + m.start())
            if out:
                return out

    # 3) «X, добрый день» + «Меня зовут» (обращение менеджера к клиенту)
    for block, start_off in search_blocks:
        for m in re.finditer(
            r"([А-ЯЁ][а-яё]+),?\s*(?:добрый\s+день|добрый\s+вечер|доброе\s+утро|здравствуйте)[.\s]*меня\s+зовут",
            block, flags=re.IGNORECASE
        ):
            name = m.group(1).strip()
            out = _accept_name(name, start_off + m.start())
            if out:
                return out

    # 3b) Ответ одним именем после «как к вам обращаться»
    for block, start_off in search_blocks:
        for m in re.finditer(
            r"(?:как\s+к\s+вам\s+обращаться|как\s+могу\s+к\s+вам\s+обращаться)\s*[?.…\s]*\s*([А-ЯЁ][а-яё]{2,14})\s*[.\s]",
            block,
            flags=re.IGNORECASE,
        ):
            name = m.group(1).strip()
            out = _accept_name(name, start_off + m.start())
            if out:
                return out

    # 4) «Алло, X?» — исходящий звонок
    for block, start_off in search_blocks:
        for m in re.finditer(r"алло[,.]?\s*([А-ЯЁ][а-яё]+)\s*[?.]", block, flags=re.IGNORECASE):
            name = m.group(1).strip()
            out = _accept_name(name, start_off + m.start())
            if out:
                return out

    # 4b) Подтверждение имени менеджером: «вас Александр, правильно?»
    for block, start_off in search_blocks:
        for m in re.finditer(
            r"\b(?:вас|вам)\s+([А-ЯЁ][а-яё]{2,20})\s*,?\s*правильн\w*\b",
            block,
            flags=re.IGNORECASE,
        ):
            name = m.group(1).strip()
            out = _accept_name(name, start_off + m.start())
            if out:
                return out

    # 5) «не затягивайте / подъезжайте / всего доброго, X»
    for block, start_off in search_blocks:
        for m in re.finditer(
            r"(?:не\s+затягивайте|подъезжайте|всего\s+доброго),?\s*([А-ЯЁ][а-яё]+)\b",
            block, flags=re.IGNORECASE
        ):
            name = m.group(1).strip()
            out = _accept_name(name, start_off + m.start())
            if out:
                return out

    # 6) Прочие обращения «X, добрый день» (без «меня зовут» сразу после)
    for block, start_off in search_blocks:
        for pattern in [
            r"г\.?\s*([А-ЯЁ][а-яё]+),?\s*(?:добрый\s+день|добрый\s+вечер|доброе\s+утро|здравствуйте)\b",
            r"([А-ЯЁ][а-яё]+),?\s*(?:добрый\s+день|добрый\s+вечер|доброе\s+утро|здравствуйте)\b(?!\s*меня)",
            r"ваше\s+имя[?]?\s*([А-ЯЁ][а-яё]+)\b",
        ]:
            for m in re.finditer(pattern, block, flags=re.IGNORECASE):
                name = m.group(1).strip()
                out = _accept_name(name, start_off + m.start())
                if out:
                    return out

    # Нет явного «как обращаться» или ответ не распознан — имя по частым обращениям в речи менеджера
    inferred = _infer_customer_name_from_repeated_mentions(
        search_low, manager_name=manager_name, admin_names=admin_names
    )
    if inferred:
        return inferred
    return None


def _customer_name_forms(name: str) -> list[str]:
    """Возвращает формы имени клиента с учётом частых STT-искажений."""
    base = (name or "").lower().strip()
    if not base:
        return []
    forms = {base}
    # 19826: STT «Алья» вместо обращения «Илья».
    if base == "илья":
        forms.add("алья")
    # Частая ошибка STT в конце имени: "Арис" <-> "Ариф".
    if len(base) >= 3 and base[-1] in ("с", "ф"):
        forms.add(base[:-1] + ("ф" if base[-1] == "с" else "с"))
    return sorted(forms)


def count_customer_name_mentions(text: str, customer_name: Optional[str]) -> int:
    """Считает обращения к клиенту по имени (варианты + простые падежные окончания)."""
    if not customer_name:
        return 0
    forms = _customer_name_forms(customer_name)
    if not forms:
        return 0
    low = (text or "").lower()
    alt = "|".join(re.escape(f) for f in forms)
    pattern = r"\b(?:" + alt + r")(?:а|у|е|ом|ой|ы|и)?\b"
    return len(re.findall(pattern, low, flags=re.IGNORECASE))


def count_customer_name_mentions_after_handover(full_transcript: str, customer_name: Optional[str]) -> int:
    """
    Обращения к клиенту по имени только после маркера перевода на менеджера (как в чек-листе ОП).
    Подрядные дубли одного и того же имени в тексте STT считаются одним обращением.
    """
    if not customer_name:
        return 0
    low = (full_transcript or "").lower().strip()
    if not low:
        return 0
    handover = RE_HANDOVER_TO_MANAGER.search(low)
    search_low = low[handover.end() :] if handover else low
    forms = _customer_name_forms(customer_name)
    if not forms:
        return 0
    alt = "|".join(re.escape(f) for f in forms)
    collapsed = re.sub(
        r"(\b(?:" + alt + r")(?:а|у|е|ом|ой|ы|и)?\b)(?:\s*[.,]?\s*\1)+",
        r"\1",
        search_low,
        flags=re.IGNORECASE,
    )
    return count_customer_name_mentions(collapsed, customer_name)


def _p12_invite_soft_patterns_match(low: str) -> bool:
    """
    П.12 «Приглашение в ДЦ»: мягкие формулировки, которых нет в жёстком словаре
    («приглашаем», «можете приехать», «при встрече» + сделка/машина, «вживую» + машина/цифры).
    """
    if not (low or "").strip():
        return False
    if re.search(r"\bприглашаем\b", low):
        return True
    if re.search(r"\bможете\s+(приехать|подъехать)\b", low):
        return True
    if re.search(r"\bможно\s+(приехать|подъехать)\b", low):
        return True
    if "мы что делаем" in low and "при встрече" in low:
        return True
    if re.search(
        r"\bпри\s+встрече\b[\s\S]{0,120}\b(машин|автомобил|предложен|окончательн|цифр|обсудим|"
        r"договор|индивиду|комплект)\w*",
        low,
        re.IGNORECASE,
    ):
        return True
    if re.search(
        r"\b(машин|автомобил|предложен|окончательн|цифр)\w*[\s\S]{0,120}\bпри\s+встрече\b",
        low,
        re.IGNORECASE,
    ):
        return True
    if re.search(
        r"\bвживую\b[\s\S]{0,72}\b(машин|автомобил|посмотрел|смотреть|познаком|цифр|авто)\w*",
        low,
        re.IGNORECASE,
    ) or re.search(
        r"\b(машин|автомобил)\w*[\s\S]{0,72}\bвживую\b",
        low,
        re.IGNORECASE,
    ):
        return True
    return False


def _p12_invite_weak_visit_probe(low: str) -> bool:
    """
    П.12 слабый сигнал (0.25): намёк на пользу личного визита без явного приглашения
    («лучше приезжать», «индивидуально приезжаете», «лучшее предложение по визиту»).
    """
    if not (low or "").strip():
        return False
    if re.search(r"\bлучше\s+приезж", low, re.IGNORECASE):
        return True
    if re.search(r"\bиндивидуаль\w*\s+приезж", low, re.IGNORECASE):
        return True
    if re.search(
        r"\bлучш\w*\s+предложен\w*\b[\s\S]{0,80}\b(?:по\s+визит\w*|при\s+визит\w*)\b",
        low,
        re.IGNORECASE,
    ):
        return True
    return False


_P7_FAMILIAR_STRONG_ZNAKOM_RE = re.compile(
    r"(знаком\w*[^.!?]{0,36}(?:автомоб\w*|машин\w*|авто\b|модел\w*)|"
    r"(?:автомоб\w*|машин\w*|авто\b|модел\w*)[^.!?]{0,36}знаком\w*)",
    re.IGNORECASE,
)


def _p7_familiar_strong_match(low: str) -> bool:
    """П.7: знакомство с авто или выяснение ожиданий/комплектации (1,0)."""
    if not (low or "").strip():
        return False
    if any(kw in low for kw in (*OP_P7_FAMILIAR_PHRASES, *OP_P7_EXPECTATIONS_PHRASES)):
        return True
    return bool(_P7_FAMILIAR_STRONG_ZNAKOM_RE.search(low))


def _p7_familiar_weak_model_cfg(low: str) -> bool:
    """
    Слабый сигнал п.7 (0,25 по рубрике): «по модели / по комплектации … определились?» —
    не формулировка «знакомы с авто», но шаг выяснения контекста выбора.
    """
    if not (low or "").strip():
        return False
    if re.search(r"\bпо\s+модел\w*\b.{0,72}\bопределил", low, re.IGNORECASE):
        return True
    if re.search(r"\bпо\s+комплектац\w*\b.{0,72}\bопределил", low, re.IGNORECASE):
        return True
    return False


def _p11_current_car_partial_probe(low: str) -> bool:
    """
    П.11 (частичное закрытие 0.5): менеджер уточняет, есть ли у клиента авто для продажи/сдачи,
    но без явной формулы «какой у вас сейчас автомобиль».
    """
    if not (low or "").strip():
        return False
    if not re.search(r"\b(автомобил|машин|авто)\w*\b", low, re.IGNORECASE):
        return False
    if re.search(
        r"\b(?:планиру\w*|будет|есть|имеется)\b[\s\S]{0,64}\b(?:продавать|продать|сдавать|сдать|на\s+обмен|"
        r"пообмену|по\s+обмену|в\s+тд|в\s+трейд(?:-|\s)?ин|в\s+трейд)\b",
        low,
        re.IGNORECASE,
    ):
        return True
    if re.search(
        r"\b(?:продавать|продать|сдавать|сдать)\b[\s\S]{0,48}\b(?:автомобил|машин|авто)\w*\b",
        low,
        re.IGNORECASE,
    ):
        return True
    return False


