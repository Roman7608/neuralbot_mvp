_STO_MANAGER_TEXT_TOKENS_CACHE: Optional[frozenset[str]] = None


def _get_sto_manager_text_tokens() -> frozenset[str]:
    """Слова из STO_MANAGERS (display, manager_name) + _STO_GREETING_NAME_TOKENS."""
    global _STO_MANAGER_TEXT_TOKENS_CACHE
    if _STO_MANAGER_TEXT_TOKENS_CACHE is not None:
        return _STO_MANAGER_TEXT_TOKENS_CACHE
    tokens: set[str] = set(_STO_GREETING_NAME_TOKENS)
    try:
        from admin_panel.managers_config import STO_MANAGERS

        for m in STO_MANAGERS:
            for key in ("manager_name", "display"):
                s = (m.get(key) or "").strip()
                for part in re.split(r"[\s,.-]+", s.lower()):
                    w = part.strip(".,;:!?\"«»")
                    if len(w) >= 2:
                        tokens.add(w)
    except ImportError:
        pass
    _STO_MANAGER_TEXT_TOKENS_CACHE = frozenset(tokens)
    return _STO_MANAGER_TEXT_TOKENS_CACHE


def _sto_in_transcript_has_directory_signal(text: str) -> bool:
    """
    True, если в транскрипте уже фигурирует роль (стажер, диспетчер, ассистент сервиса)
    или имя/фамилия из справочника СТО — тогда авто-приветствие не вставляем.
    """
    if not (text or "").strip():
        return False
    tl = text.lower()
    for pat in _STO_IN_ROLE_PATTERNS:
        if re.search(pat, tl):
            return True
    for tok in _get_sto_manager_text_tokens():
        if len(tok) < 2:
            continue
        if re.search(r"\b" + re.escape(tok) + r"\b", tl):
            return True
        if len(tok) >= 4 and tok in tl:
            return True
    return False


def _sto_in_body_shop_before_first_greeting(text: str, greet_start: int) -> bool:
    """
    До первого «Здравствуйте»: мастер кузова ИЛИ «кузовн…» + сотрудник из KUZOV_BODY_MANAGERS
    (имя/фамилия в префиксе после первого «кузовн») — не подставляем канон стажёра (ид 1652 и аналоги).
    """
    if greet_start <= 0:
        return False
    prefix = (text or "")[:greet_start].lower()
    if not prefix.strip():
        return False
    if re.search(r"\bмастер\s+кузовн", prefix):
        return True
    ik = prefix.find("кузовн")
    if ik < 0:
        return False
    after_kuzov = prefix[ik:]
    try:
        from admin_panel.managers_config import get_kuzov_body_word_tokens

        tokens = get_kuzov_body_word_tokens()
    except ImportError:
        tokens = frozenset()
    for tok in tokens:
        if len(tok) < 3:
            continue
        if re.search(r"\b" + re.escape(tok) + r"\b", after_kuzov):
            return True
    return False


