def _sto_in_skip_augment_for_admin_then_client_greeting(
    text: str, greet_start: int, greet_end: int
) -> bool:
    """
    Администратор/официальный дилер + «добрый день» (и варианты) в префиксе, затем «здравствуйте»
    и сразу слова клиента (я, звонил, …) — не подменять это приветствие на канон стажёра.
    """
    prefix = text[:greet_start].lower()
    admin_ok = (
        "администратор" in prefix
        or "официальный дилер" in prefix
        or ("официальный" in prefix and "дилер" in prefix)
    )
    if not admin_ok:
        return False
    best = -1
    for phrase in _STO_IN_ADMIN_GREETING_PHRASES:
        p = prefix.rfind(phrase)
        if p > best:
            best = p
    if best < 0:
        return False
    after = text[greet_end:].lstrip()
    wm = re.match(r"([а-яё]{2,}(?:-[а-яё]{2,})?)", after, re.IGNORECASE)
    if not wm:
        return False
    w0 = wm.group(1).lower().strip(".,;:!?\"«»")
    return w0 in _STO_IN_CLIENT_FIRST_WORD_AFTER_HELLO


def augment_sto_in_greeting_if_needed(transcript: str, department: str, call_type: str) -> str:
    """
    Для СТО входящего: если после очередного «Здравствуйте» в следующих 1–3 словах нет имени/фамилии
    из справочника ассистентов и стажёра СТО, это «Здравствуйте» заменяется на стандартную строку
    с названием и «стажер Дарья» (остальной текст не режется).

    Если до позиции этого «Здравствуйте» в тексте уже есть роль (стажер, диспетчер, ассистент сервиса)
    или имя из справочника СТО — эту позицию пропускаем и ищем следующее «Здравствуйте»
    (чтобы не дублировать канон после нормализации «двойного здравствуйте» после перевода).

    После администратора и «добрый день» первое «здравствуйте» с репликой клиента (я, звонил, …)
    не подменяется; подстановка может сработать на следующем подходящем «здравствуйте».

    Если до кандидата «Здравствуйте» уже «мастер кузовн…» или связка «кузовн…» + имя/фамилия из
    справочника кузовного цеха (managers_config.get_kuzov_body_word_tokens) — кандидат пропускается.
    """
    if not _sto_canon_greeting_in_transcript_enabled():
        return transcript
    if (department or "").strip().upper() != "STO" or (call_type or "").strip().upper() != "STO_IN":
        return transcript
    text = transcript or ""
    if not text.strip():
        return text
    search_from = 0
    while True:
        m = re.search(r"\bздравствуйте\b", text[search_from:], flags=re.IGNORECASE)
        if not m:
            return transcript
        abs_start = search_from + m.start()
        abs_end = search_from + m.end()
        search_from = abs_end
        if _sto_in_transcript_has_directory_signal(text[:abs_start]):
            continue
        if _sto_in_body_shop_before_first_greeting(text, abs_start):
            continue
        if _sto_in_skip_augment_for_admin_then_client_greeting(text, abs_start, abs_end):
            continue
        after = text[abs_end:]
        rest = after.lstrip()
        collected = []
        i = 0
        while len(collected) < 3 and i < len(rest):
            while i < len(rest) and rest[i] in " \t\n\r.,!?;:\"«»—–-":
                i += 1
            if i >= len(rest):
                break
            wm = re.match(r"([а-яёА-ЯЁ]{2,}(?:-[а-яёА-ЯЁ]{2,})?)", rest[i:])
            if not wm:
                break
            word = wm.group(1).lower().strip(".,;:!?\"«»")
            collected.append(word)
            i += wm.end()
        skip_name = False
        for w in collected:
            if w in _STO_GREETING_NAME_TOKENS:
                skip_name = True
                break
            for tok in _STO_GREETING_NAME_TOKENS:
                if len(tok) >= 4 and tok in w:
                    skip_name = True
                    break
            if skip_name:
                break
        if skip_name:
            continue
        # «Здравствуйте» + сразу второе приветствие времени суток — не канон стажёра (без требования «админ» в префиксе)
        if collected and collected[0] in ("доброе", "добрый"):
            continue
        replacement = _STO_IN_GREETING_STANDARD
        orig = text[abs_start:abs_end]
        if orig and orig[0].isupper():
            replacement = replacement[0].upper() + replacement[1:]
        return text[:abs_start] + replacement + text[abs_end:]


# Нормализация локальной LLM (USE_LLM_NORMALIZE=1, NORMALIZE_LLM_MODEL_PATH или LLM_MODEL_PATH или config.LLM_MODEL_PATH)
_USE_LLM_NORMALIZE = os.environ.get("USE_LLM_NORMALIZE", "").strip().lower() in ("1", "true", "yes")


def _get_llm_model_path() -> str:
    p = os.environ.get("NORMALIZE_LLM_MODEL_PATH", "").strip() or os.environ.get("LLM_MODEL_PATH", "").strip()
    if p:
        return p
    try:
        from config import LLM_MODEL_PATH
        return (LLM_MODEL_PATH or "").strip()
    except ImportError:
        return ""


_NORMALIZE_LLM_MODEL_PATH = _get_llm_model_path()
_llm_model_cache: Optional[object] = None


def _split_text_for_llm(text: str, max_chunk_chars: int = 3000) -> list:
    """Разбивает текст на чанки по max_chunk_chars, по границам предложений или пробелов."""
    text = (text or "").strip()
    if not text or len(text) <= max_chunk_chars:
        return [text] if text else []
    chunks = []
    rest = text
    while rest:
        if len(rest) <= max_chunk_chars:
            chunks.append(rest.strip())
            break
        block = rest[: max_chunk_chars + 1]
        last_dot = block.rfind(". ")
        last_newline = block.rfind("\n")
        split_at = max(last_dot, last_newline)
        if split_at <= 0:
            split_at = block.rfind(" ")
        if split_at <= 0:
            split_at = max_chunk_chars
        chunk = rest[: split_at + 1].strip()
        if chunk:
            chunks.append(chunk)
        rest = rest[split_at + 1 :].lstrip()
    return chunks


def normalize_with_llm(text: str, model_path: Optional[str] = None) -> str:
    """
    Дополнительная нормализация текста транскрипции локальной LLM (llama-cpp-python).
    Исправляет оставшиеся ошибки STT, бренды (Чери, Tenet, Tiggo, Викинги и т.д.).
    Длинный текст обрабатывается по чанкам, чтобы не обрезать вывод.
    При ошибке или недоступности модели возвращает text без изменений.
    """
    if not (text or "").strip():
        return text
    path = (model_path or _NORMALIZE_LLM_MODEL_PATH).strip()
    if not path or not os.path.isfile(path):
        return text
    try:
        from llama_cpp import Llama
    except ImportError:
        return text
    global _llm_model_cache
    prompt_tpl = """Исправь в тексте только очевидные ошибки распознавания речи (STT) и названия.
Правила: Чери (не Чрри, Черrри, Cherri, Чиреви, Череви, Чиикинги и т.п.), Викинги на Заставной (не Вдинкина),
Tenet (не Тено, Тнет, ТН), Tiggo (не тига, тигго с ошибками), трейд-ин, парктроник, Kia Rio и т.п. Цифры и смысл не меняй.
Ответь одним текстом — только исправленный текст, без пояснений.

Текст:
---
"""
    try:
        if _llm_model_cache is None:
            _llm_model_cache = Llama(model_path=path, n_ctx=2048, n_gpu_layers=-1, verbose=False)
        llm = _llm_model_cache
        chunks = _split_text_for_llm((text or "").strip(), max_chunk_chars=3000)
        if not chunks:
            return text
        results = []
        for i, chunk in enumerate(chunks):
            if not chunk.strip():
                continue
            print(f"  LLM нормализация… ({i + 1}/{len(chunks)})", flush=True)
            prompt = prompt_tpl + chunk + "\n---"
            out = llm(prompt, max_tokens=2048, stop=["</s>", "###", "\n\nТекст:", "\n\nТекст ", "--- (", "---("], stream=False)
            raw = (out.get("choices", [{}])[0].get("text", "") or "").strip()
            # Убрать артефакты ответа: «--- (исправленный текст) ---», «(написать только исправленный текст)»
            raw = re.sub(r"^---\s*\([^)]*\)\s*---\s*", "", raw)
            raw = re.sub(r"^\(написать только исправленный текст\)\s*", "", raw, flags=re.IGNORECASE)
            if raw and len(raw) > 20:
                results.append(raw)
            else:
                results.append(chunk)
        if results:
            return " ".join(results)
    except Exception:
        pass
    return text


# Известные варианты имён: вариант -> каноническое написание (целиком по слову).
_NAME_VARIANTS_TO_CANONICAL = {
    "Алек": "Алик",
    "алек": "Алик",
    "Олег": "Алик",
    "олег": "Алик",
    "Николаи": "Николай",
    "николаи": "Николай",
    "Зуслан": "Рустам",
    "зуслан": "Рустам",
}


def _edit_distance_one(a: str, b: str) -> bool:
    """True, если слова отличаются не более чем на 1 символ (замена/вставка/удаление)."""
    if abs(len(a) - len(b)) > 1:
        return False
    if len(a) > len(b):
        a, b = b, a
    # len(a) <= len(b)
    if len(a) == len(b):
        return sum(1 for x, y in zip(a, b) if x != y) <= 1
    # len(b) == len(a) + 1
    i = 0
    for c in b:
        if i < len(a) and a[i] == c:
            i += 1
    return i == len(a)


def _unify_name_variants_in_document(text: str) -> str:
    """
    В пределах одного текста находит похожие короткие слова (кандидаты в имена),
    объединяет варианты написания в одно (по самому частому).
    """
    if not (text or "").strip():
        return text
    # Слова 3–12 букв, только буквы
    word_re = re.compile(r"\b([а-яёa-z]{3,12})\b", re.IGNORECASE)
    tokens = word_re.findall(text)
    from collections import Counter
    counts = Counter(tokens)
    # Кандидаты: встречаются минимум 2 раза
    candidates = [w for w, c in counts.items() if c >= 2 and len(w) >= 3]
    if not candidates:
        return text
    # Группы похожих (расстояние 1)
    used = set()
    groups = []
    for w in candidates:
        if w in used:
            continue
        group = [w]
        used.add(w)
        for other in candidates:
            if other in used:
                continue
            if _edit_distance_one(w, other):
                group.append(other)
                used.add(other)
        if len(group) >= 2:
            groups.append(group)
    # В каждой группе — к самому частому, остальные заменяем
    for group in groups:
        canonical = max(group, key=lambda w: counts[w])
        for variant in group:
            if variant == canonical:
                continue
            text = re.sub(r"\b" + re.escape(variant) + r"\b", canonical, text, flags=re.IGNORECASE)
    return text


def unify_name_variants(text: str) -> str:
    """
    Приводит варианты имён в тексте к одному написанию:
    1) словарь известных пар (Алик -> Алек и т.д.);
    2) в пределах документа — похожие короткие слова к самому частому варианту.
    """
    if not (text or "").strip():
        return text
    # 1) Известные варианты
    for variant, canonical in _NAME_VARIANTS_TO_CANONICAL.items():
        text = re.sub(r"\b" + re.escape(variant) + r"\b", canonical, text, flags=re.IGNORECASE)
    # 2) По документу
    text = _unify_name_variants_in_document(text)
    return text


def normalize_transcript(transcript: str) -> str:
    """
    Нормализация: сначала правила (regex), затем опционально LLM, затем унификация имён.
    USE_LLM_NORMALIZE=1 и NORMALIZE_LLM_MODEL_PATH (или LLM_MODEL_PATH) — для прохода LLM.
    После LLM — повторное удаление вариантов в скобках (не X, Y, Z).
    """
    normalized = normalize_text(transcript)
    if _USE_LLM_NORMALIZE and _NORMALIZE_LLM_MODEL_PATH:
        normalized = normalize_with_llm(normalized)
        # Повторно удалить (не ...) и артефакты «--- (исправленный текст) ---»
        normalized = re.sub(r"\s*\(не\s+[^)]+\)", " ", normalized)
        normalized = re.sub(r"\s*---\s*\([^)]*\)\s*---\s*", " ", normalized)
        normalized = re.sub(r"\s{2,}", " ", normalized).strip()
    normalized = unify_name_variants(normalized)
    return normalized

